-- ทำไมต้องมี: การนับแถวจับ *ของหาย* ได้ แต่จับ *ของเพี้ยน* ไม่ได้
--             เคสที่กัดจริง (`cover_image_path` → 502) เป็นชนิดเพี้ยน ไม่ใช่หาย
-- คืนอะไร:    ลายนิ้วมือ ไม่ใช่ข้อมูล → ที่อยู่บ้านใน custom_places ไม่ออกจากฐานสักตัวอักษร
--
-- 🔴 นี่คือ **ตัวสร้างคิวรี** ไม่ใช่ตัวคิวรีเอง — มันอ่าน information_schema สด
--    จึงครอบตารางที่เพิ่งเพิ่มโดยไม่ต้องมีใครมาเติมรายชื่อ **ล้าสมัยไม่ได้ตามนิยาม**
--    (ถ้าเก็บผลลัพธ์แทน มันจะกลายเป็นทะเบียนที่ไม่มีอะไรบอกว่าล้า)
--
-- วิธีใช้ — สองขั้น:
--   1) รันไฟล์นี้ → ได้ SQL ออกมาก้อนหนึ่ง
--   2) รัน SQL ก้อนนั้น → ได้ตาราง (tbl, rows, fp) เก็บไว้เทียบ
--   ทำทั้งสองขั้น **ก่อน** migrate แล้วทำซ้ำ **หลัง** migrate · fp ต้องตรงทุกบรรทัด
--
-- กติกาที่ฝังอยู่ในตัวสร้างนี้แล้ว (ตัดสินไว้ตอนออกแบบ AC2):
--   ① ตัด id / updated_at ออก — ขยับเองโดยความหมายไม่เปลี่ยน · ลายนิ้วมือที่เปลี่ยนทุกครั้งไม่บอกอะไร
--   ② order by ตายตัว — ที่นี่เรียงด้วย *เนื้อ* ไม่ใช่ id
--      🔴 ต่างจากฉบับที่ backlog.md อธิบายไว้ (`order by <คีย์ตายตัว>`) โดยตั้งใจ:
--         เรียงด้วย id แล้วถ้า migrate แจก id ใหม่ ลายนิ้วมือจะเปลี่ยนทั้งที่เนื้อเท่าเดิม
--         เรียงด้วยเนื้อ → ไม่ขึ้นกับทั้งลำดับแถวและการเปลี่ยน id
--   ③ เทียบได้เฉพาะ ฐานเดียวกัน ก่อน–หลัง — prod กับ dev ไม่มีวันตรงเพราะข้อมูลคนละชุดโดยตั้งใจ
--   ④ NULL แทนด้วย '<N>' ไม่ใช่ปล่อยหาย — ไม่งั้น (a,NULL,b) กับ (a,b,NULL) ชนกัน
--
-- ✅ ทดสอบแล้วจริง 29 ส.ค. 2026 (P1) บน PostgreSQL 17.11 ในเครื่อง
--    ที่ restore จาก trip-schema.sql + trip-data.sql — **ไม่ได้ทดสอบบนฐานจริง**
--    ยิง 4 ทิศบน trip_stops (71 แถว) ใน begin/rollback:
--      เขียนทับ 71 แถวด้วยค่าเดิม  → fp เท่าเดิม  (ไม่ขึ้นกับลำดับแถว)
--      แก้ 1 ช่อง เพิ่ม 1 ตัวอักษร → fp เปลี่ยน   (จับของเพี้ยน)
--      ลบ 1 แถว                    → fp เปลี่ยน   (จับของหาย)
--      แก้ updated_at ทุกแถว       → fp เท่าเดิม  (กติกา ① ทำงานจริง)
--    🔴 สองทิศแรกสำคัญที่สุด — ถ้าไม่ยิง "fp ตรงกัน" จะแยกไม่ออกจาก "fp ไม่เคยวัดอะไร"

select
  'select ' || quote_literal(table_name) || ' as tbl, count(*) as rows, '
  || 'md5(string_agg(c, E''\n'' order by c)) as fp from (select array_to_string(array['
  || string_agg('coalesce(' || quote_ident(column_name) || '::text, ''<N>'')', ', '
       order by ordinal_position)
  || '], ''|'') as c from public.' || quote_ident(table_name) || ') s'
  || case when row_number() over (order by table_name) < count(*) over () then E'\nunion all' else ';' end
from information_schema.columns
where table_schema = 'public'
  and column_name not in ('id', 'updated_at')
group by table_name
order by table_name;
