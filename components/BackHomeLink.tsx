"use client";

import Link from "next/link";
import { E5_COPY } from "@/lib/i18n";

/**
 * **ปุ่มกลับหน้าแรก — ใบเดียวของทั้งเว็บ** · เจ้าของ: P2-UI/UX · 5 ก.ย. 2026
 * ผู้ใช้สั่งเอง: *"ทำปุ่มกลับหน้าแรกให้ดีและตั้งใจ **ใช้เหมือนกันทั้งเว็บ** … ทั้งคำ และลักษณะ รูปร่าง"*
 *
 * ## 🔴 ก่อนหน้านี้มี **ห้าแบบ** ที่ไปที่เดียวกัน
 * ```
 * /account            ปุ่มขอบมน  "← กลับหน้าหลัก"
 * /explore/[id]       ตัวหนังสือเทาเล็ก ๆ  "← หน้าแรก"        ← ผู้ใช้ส่งภาพนี้มา
 * หน้ารับคำชวน         กล่องขอบ  "ไปหน้าแรก"
 * แถบหัวหน้าทริป       ปุ่มบนพื้นเข้ม  "🏠 ทริปทั้งหมด"
 * ```
 * 🎯 ***สี่คำเรียกสำหรับที่เดียวกัน ⇒ ผู้ใช้ต้องเดาใหม่ทุกหน้าว่าอันไหนพากลับ***
 * · และมันเกิดโดยไม่มีใครตัดสินใจ — **แต่ละใบถูกเขียนตอนทำหน้านั้น ๆ โดยไม่มีที่กลางให้หยิบ**
 *
 * ## 🔴 คำเดียว: **"กลับหน้าหลัก"**
 * ผู้ใช้เลือกคำนี้เองตอนสั่งแก้หน้า `/account` (*"ควรแก้คำเป็น กลับหน้าหลัก"*) ⇒ ยึดคำของเขา
 * ⚠️ **ไม่ใช่ "ทริปทั้งหมด"** — หน้าแรกไม่ได้มีแค่รายการทริปแล้ว (มี *"ไปไหนดี?"* และทริปแนะนำด้วย)
 *    🎯 ***ปุ่มย้อนกลับควรบอก *ที่ที่จะไป* ไม่ใช่ *ส่วนหนึ่งของสิ่งที่อยู่ที่นั่น****
 *
 * ## 🔴 `tone` มีสองค่า และทั้งคู่ถูกใช้จริง — ไม่ใช่ปุ่มเผื่ออนาคต
 * ```
 * "surface"  บนพื้นหน้า (ครีม/เข้มตามธีม)   ← ค่าเริ่มต้น · ใช้ 3 ที่
 * "brand"    บนแถบหัวสีเขียวเข้ม            ← หน้าทริป · พื้นตายตัว ไม่พลิกตามธีม
 * ```
 * 🎯 **ความต่างมาจาก *พื้นที่มันวางอยู่* ไม่ใช่รสนิยม** — แถบหัวเป็นสีแบรนด์ทึบ ซึ่งไม่พลิกตามธีม
 * ⇒ ใช้โทเคนชุดเดียวกับพื้นหน้าไม่ได้ · **คนละพื้น ต้องคนละคู่สี** (กติกาเดียวกับที่ `globals.css` ใช้ทั้งไฟล์)
 *
 * ## 📌 พื้นที่กดกว้างกว่าที่เห็น
 * `before:-inset-[7px]` ⇒ พื้นที่แตะจริงใหญ่กว่ากรอบที่มองเห็น **โดยไม่ดันเลย์เอาต์รอบ ๆ**
 * (ยกมาจากปุ่มเดิมของหน้า `/account` ซึ่งเป็นใบที่ถูกคิดมาแล้วมากที่สุดในสี่ใบ)
 */
export function BackHomeLink({
  tone = "surface",
  className = "",
}: {
  tone?: "surface" | "brand";
  className?: string;
}) {
  const base =
    "relative inline-flex items-center gap-1.5 rounded-pill px-3 py-1.5 text-sm font-medium transition-colors before:absolute before:-inset-[7px] before:content-['']";
  const skin =
    tone === "brand"
      ? "bg-cream/10 text-cream hover:bg-cream/20"
      : /* 🔴 `border-action-outline` ไม่ใช่ `border-line` — ธีมมืด `--line` ได้ 1.43:1 กับพื้น
           ⇒ ปุ่มแทบไม่มีรูปร่าง (ผู้ใช้รายงานเอง 4 ก.ย. 2026) · ขอบ *ปุ่ม* กับเส้นคั่น *เนื้อหา* คนละหน้าที่ */
        "border border-action-outline bg-surface-raised text-content hover:border-pine hover:text-pine";

  return (
    <Link href="/" className={`${base} ${skin} ${className}`}>
      <span aria-hidden>←</span>
      {E5_COPY.home.backHome}
    </Link>
  );
}
