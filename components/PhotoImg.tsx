"use client";

import { type ReactNode, useState } from "react";

/**
 * `<img>` ของรูปสถานที่ ที่มี **ทางลงเมื่อโหลดไม่สำเร็จ** — ผู้ใช้รายงานเอง 4 ก.ย. 2026 (*"ภาพบางที่มันฉีกขาด"*)
 *
 * ## 🔴 ช่องที่ปิด — สามสภาพ ไม่ใช่สอง
 * ทั้ง `PlaceThumb` · `PlaceCard` · `PhotoGallery` มีทางลงครบสองทางอยู่แล้ว:
 * ```
 * กำลังโหลด          → โครงกระพริบ
 * ไม่มีรูป            → ไทล์สีหมวด / อิโมจิ
 * **มีรูปแต่โหลดไม่ได้**  → **ไม่มีทางลง** ⇒ เบราว์เซอร์วาดไอคอนรูปแตก
 * ```
 * 🎯 ***สภาพที่สามไม่ได้หายไปเพราะไม่มีใครคิดถึง — มันหายไปเพราะสองสภาพแรกอ่านเหมือนครบแล้ว***
 *
 * ## ทำไมมันเพิ่งโผล่วันนี้ ทั้งที่โค้ดเดิมมานาน
 * คลังโตจาก 202 → 2,396 แห่งในวันเดียว แต่ `place_photo_cache` มี 183 แถว
 * ⇒ **92% ของสถานที่ยังไม่มีรูปในแคช ต้องยิง Google สดตอนเปิดหน้า** · ยิงพร้อมกันเยอะ บางใบไม่ผ่าน
 * → `/api/place-photo` คืน **JSON 502** ให้ `<img>` → รูปแตก
 * · 🔴 **รากจริงคือ cron อุ่นแคชยังไม่เคยยิงสักรอบ** — ใบนี้แก้*อาการ* ไม่ได้แก้ราก
 *   วันที่แคชครอบคลังแล้ว โค้ดนี้จะแทบไม่ถูกเรียก **และนั่นคือสภาพที่ถูก ไม่ใช่สัญญาณว่ามันไม่จำเป็น**
 *
 * ## ⚠️ ที่จงใจไม่ทำ
 * · **ไม่ลองรูปถัดไปใน `photos[]`** — ถ้าเหตุคือชนเพดานอัตรา ใบถัดไปก็ล้มเหมือนกัน
 *   ได้คำขอเพิ่มโดยไม่ได้อะไรกลับ
 * · **ไม่นับ/ไม่ส่งสัญญาณว่ามีกี่ใบที่ล้ม** — จะกลายเป็นกลไกใหม่ที่ยังไม่มีใครสั่ง
 *   🔴 **จดไว้ว่าเป็นช่องที่รู้อยู่:** หลังใบนี้ลง ผู้ใช้จะเห็นไทล์สะอาดแทนรูปแตก
 *   **แต่เราจะไม่รู้ว่ามันเกิดบ่อยแค่ไหน** — ต้องดูจาก 502 ของ route แทน ซึ่งวันนี้ยังไม่มีใครนับ
 */
export function PhotoImg({
  src,
  className,
  fallback,
}: {
  src: string;
  className?: string;
  /** สิ่งที่แสดงแทนเมื่อรูปโหลดไม่ได้ — ควรเป็นตัวเดียวกับตอน "ไม่มีรูป" ไม่งั้นสองสภาพจะดูต่างกันโดยไม่มีเหตุผล */
  fallback: ReactNode;
}) {
  /**
   * 🔴 เก็บ **`src` ที่ล้ม** ไม่ใช่ `boolean`
   * รายการสถานที่ใช้ตำแหน่งซ้ำตอน re-render (คนละสถานที่ ตำแหน่งเดิม) — ถ้าเก็บเป็น `boolean`
   * สถานที่ใหม่จะรับสถานะ "ล้ม" ของสถานที่เก่ามา **แล้วไม่มีวันลองโหลดเลย**
   * ⇒ เทียบกับ `src` ปัจจุบันทำให้มันรีเซ็ตตัวเองเมื่อรูปเปลี่ยน โดยผู้เรียกไม่ต้องใส่ `key`
   */
  const [failedSrc, setFailedSrc] = useState<string | null>(null);
  if (failedSrc === src) return <>{fallback}</>;

  return (
    // eslint-disable-next-line @next/next/no-img-element
    <img
      src={src}
      alt=""
      loading="lazy"
      className={className}
      onError={() => setFailedSrc(src)}
    />
  );
}
