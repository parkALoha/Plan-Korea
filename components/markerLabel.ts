/** หมึกที่เข้มกว่า `--color-ink` (#2b241f) — บน #d9683a ค่าเดิมได้แค่ 4.36:1 ยังไม่ผ่าน */
export const MARKER_LABEL_INK = "#1a1512";
export const MARKER_LABEL_LIGHT = "#ffffff";

/** ความสว่างสัมพัทธ์ตามนิยาม WCAG 2.x */
function relativeLuminance(hex: string): number {
  const h = hex.replace("#", "");
  const ch = [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16) / 255);
  const lin = ch.map((v) => (v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4));
  return 0.2126 * lin[0] + 0.7152 * lin[1] + 0.0722 * lin[2];
}

export function contrastRatio(a: string, b: string): number {
  const [x, y] = [relativeLuminance(a), relativeLuminance(b)];
  return (Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05);
}

/**
 * เลือกสีตัวอักษรที่คอนทราสต์กับพื้นมากกว่า
 * — เป็น *กติกา* ไม่ใช่ตารางข้อยกเว้นรายหมวด ⇒ เพิ่มหมวดใหม่แล้วยังทำงานถูกเอง
 *   (แต่ไม่รับประกันว่าจะ *ผ่านเกณฑ์* — นั่นเป็นหน้าที่ของเทสต์ที่วนทุกหมวดจริง)
 */
export function markerLabelColor(background: string): string {
  return contrastRatio(MARKER_LABEL_LIGHT, background) >= contrastRatio(MARKER_LABEL_INK, background)
    ? MARKER_LABEL_LIGHT
    : MARKER_LABEL_INK;
}
