"use client";

import Link from "next/link";
import type { ReactNode } from "react";

/**
 * **เปลือกการ์ดในกริดเลือกของ** — ใช้ร่วมกันทุกชนิด: ทริปของฉัน · เมืองปลายทาง · (กำลังมา) ทริปแนะนำ
 * เจ้าของ: P2-UI/UX · 4 ก.ย. 2026 · **ผู้ใช้สั่งเอง และเป็นรอบที่สองของข้อเดียวกัน**
 *
 * ```
 * รอบแรก   "มันควรมีอะไรที่เหมือนกัน เช่นการวางบรรทัดของข้อความ และ icon"   → พูดถึง **การจัดวาง**
 * รอบสอง   "รูปแบบ มันควรใช้ component เดียวกับพวกนี้นะ"                  → พูดถึง **โค้ดตัวเดียวกัน**
 * ```
 * 🎯 ***เขาไม่ได้ขอให้ "หน้าตาคล้าย" — เขาขอให้ "เป็นตัวเดียวกัน"***
 * ⇒ แก้ด้วยการก๊อป class ไปวางจะกลับมารอบสาม · ไฟล์นี้คือที่ที่ *เปลือก* มีอยู่ที่เดียวจริง ๆ
 *
 * ## 🔴 เปลือกถือ *โครง* · ผู้เรียกถือ *เนื้อ* — และเส้นแบ่งนี้ตั้งใจ
 * เปลือก: ขอบ · มุม · พื้น · hover/focus · ตำแหน่งป้ายมุมขวาบน · ระยะขอบใน · สไตล์ชื่อ
 * ผู้เรียก: รูปปก (ไล่ fallback เอง) · บรรทัดใต้ชื่อ (`children`) · ป้าย (ถ้ามี)
 *
 * 🔴 **ห้ามบังคับให้ทุกใบมีครบทุกช่อง** (P1 เตือน · ถูก) — การ์ดเมือง **ไม่มีความหมาย**
 * ให้ใส่ "อีก 18 วัน" · ช่วงวันที่ · จำนวนสมาชิก · ถ้าเปลือกบังคับ มันจะต้องเติมของปลอม
 * ซึ่งเป็นสิ่งเดียวกับที่เราเพิ่งปฏิเสธไปตอนไม่ใส่ *"ยังไม่ระบุเมือง"* ลงการ์ดทริปที่ไม่มีจุดหมาย
 * ✅ ทุกช่องเป็น *ทางเลือก* · ***ช่องที่มีที่ว่างแต่ว่างได้*** คือคำตอบ ไม่ใช่ช่องที่ต้องกรอก
 *
 * ## 🔴 **รูปการ์ดมีแบบเดียวทั้งเว็บ ทุกขนาดจอ — และ *ไม่มีพารามิเตอร์ให้เลือก* โดยตั้งใจ**
 * ***รูปเป็นแบนเนอร์แนวนอนอยู่ด้านบนเสมอ*** ทุกใบ ทุกที่ ทุกความกว้างจอ
 *
 * ⚠️ **เคยแยกเป็นแถบด้านซ้ายบนมือถือ** เพื่อให้เห็นการ์ดต่อจอเยอะขึ้น (วัดได้ **4.9 ใบ** เทียบ ~2.6)
 * 🔴 **ผู้ใช้ตั้งคำถามเอง แล้วตอบเอง** (4 ก.ย. 2026):
 * > *"ในมุมมองมือถือ component ทั้งหมด ภาพควรจะเป็นแนวนอนไหมนะ เพราะส่วนมากเขาคงมาเป็นแนวนอน"*
 * > *"ทำไสตล์เดียวกับในคอมได้ไหม"*
 * 🎯 ***และเหตุผลของเขาคือเหตุผลเรื่อง *แหล่งที่มาของรูป* ไม่ใช่เรื่องรสนิยม*** —
 *    รูปสถานที่แทบทุกใบเป็นแนวนอน · แถบซ้ายกว้าง 96px สูง 121px (อัตราส่วน **0.79 = แนวตั้ง**)
 *    ⇒ รูปแนวนอนถูกครอบตัดจนเหลือแถบกลางภาพ **ซึ่งมักไม่มีอะไรบอกว่าเป็นที่ไหน**
 * 🔴 **ในเลย์เอาต์แบบแถบข้าง รูปแนวนอนเป็นไปไม่ได้ตามโครงสร้าง** — ความสูงของรูปถูกบังคับด้วย
 *    ความสูงของการ์ด ซึ่งถูกบังคับด้วยจำนวนบรรทัดข้อความ ⇒ จะกว้างกว่าสูงได้ ต้องยอมให้การ์ดเตี้ยกว่าข้อความ
 *    ⇒ **ทางเดียวที่ได้รูปแนวนอนจริงคือย้ายรูปขึ้นด้านบน** · ราคาที่จ่ายคือความหนาแน่น (จดไว้ข้างบน)
 *
 * ## 🔴 **ปกต้องกำหนดด้วย *อัตราส่วน* ไม่ใช่ *ความสูงเป็นพิกเซล*** (ผู้ใช้ถาม: *"ขนาดรูปภาพ และขนาดของส่วนข้อมูล สมมาตรยัง"*)
 * ความสูงคงที่ `h-28` อ่านเหมือนคงที่ **แต่การ์ดกว้างไม่เท่ากันในแต่ละจอ** ⇒ อัตราส่วนของ *รูป* เปลี่ยนตามจอ:
 * ```
 * มือถือ  การ์ด 341px · ปกสูง 112 → **3.04 : 1**   ← แบนกว่า
 * คอม     การ์ด 292px · ปกสูง 112 → **2.60 : 1**
 * ```
 * 🎯 ***"ความสูงเท่ากันทุกจอ" กับ "รูปเป็นทรงเดียวกันทุกจอ" เป็นคนละอย่าง — และคนละอย่างนั้น
 *    มองไม่เห็นจากโค้ด เพราะเลขที่เขียนไว้คือเลขเดียวกัน (`h-28`)***
 * · รูปเดียวกันจึงถูกครอบไม่เท่ากันบนสองจอ ⇒ **สิ่งที่ผู้ใช้เห็นในภาพ ไม่ใช่สิ่งเดียวกัน**
 * ✅ `aspect-[5/2]` ⇒ ทรงเดียวกันทุกความกว้าง · และเลือก `2.5` เพราะทำให้ **สูงของปก ≈ สูงของบล็อกข้อมูล**
 *   บนมือถือ (สมดุลราว 1:1) ซึ่งเป็นสิ่งที่คำถามถามถึงตรง ๆ
 *
 * ⚠️ **เคยมี `coverLayout` ให้เลือก `"banner"` / `"adaptive"`** ด้วยเหตุผลที่ *เคยจริง*:
 * กริดเมืองเคยเป็น 2 คอลัมน์ตั้งแต่มือถือ (การ์ดกว้าง ~152px) ⇒ แถบข้างจะแคบเกินไป
 * 🔴 **แต่ตอนผู้ใช้สั่งให้การ์ดประเทศ/เมืองใหญ่เท่าการ์ดทริป กริดทุกอันกลายเป็น `17rem` เหมือนกันหมด**
 *    ⇒ เหตุผลนั้นตายตั้งแต่วันนั้น · **ไม่มีใครไปแก้ค่าที่มันค้ำอยู่ เพราะมันอยู่คนละไฟล์กับสิ่งที่เปลี่ยน**
 *    ผลคือหน้าเดียวกันมีการ์ดสองทรง จนผู้ใช้ทักเอง (4 ก.ย. 2026): *"component ของทั้งเว็บ … เหมือนกัน เท่ากัน หรือยัง"*
 *
 * 🎯 ***ตัด "ทางที่จะต่างกัน" ทิ้ง ไม่ใช่ตั้งค่าให้ทุกที่ตรงกัน*** — อย่างหลังต้องมีคนคอยดูแลให้ตรงตลอดไป
 *    และวันที่มันเพี้ยน **จะไม่มีอะไรส่งเสียง** (รูปเดียวกับที่เราตัดเอกสารสองฉบับทิ้งเหลือใบเดียว)
 * · ต้องการทรงอื่นจริง ๆ วันหลัง: เพิ่มกลับได้ **แต่ต้องเขียนว่าอะไรทำให้มันจำเป็น และอะไรจะทำให้มันหมดอายุ**
 */
export function CoverCard({
  href,
  onClick,
  cover,
  badge,
  title,
  titleTrailing,
  titleClassName = "text-base font-bold leading-snug sm:text-lg",
  children,
}: {
  /** ลิงก์ — ใส่อย่างใดอย่างหนึ่งกับ `onClick` (การ์ดทริปเป็นลิงก์ · การ์ดเมืองเป็นปุ่มเปิดฟอร์ม) */
  href?: string;
  onClick?: () => void;
  /** รูปปก — **ผู้เรียกไล่ fallback เอง** เพราะแต่ละชนิดมีชั้นไม่เท่ากัน (เมือง→ประเทศ→พื้นไล่สี ฯลฯ) */
  cover: ReactNode;
  /** ป้ายมุมขวาบน — ไม่มีก็ได้ · เกาะ **การ์ด** ไม่ใช่เกาะรูป (บนมือถือรูปเป็นแถบแคบ ป้ายจะทับงานศิลป์) */
  badge?: ReactNode;
  title: ReactNode;
  /**
   * ของที่อยู่ **ขวาสุดของบรรทัดชื่อ** — ไม่มีก็ได้ (ผู้ใช้เสนอเอง 4 ก.ย. 2026:
   * *"การวางตำแหน่งสมาชิกในทริป ควรย้ายไปด้านขวา แต่บรรทัดเดียวกับชื่อทริป"*)
   *
   * 🔴 **เป็นช่อง *ทางเลือก* ไม่ใช่ช่องบังคับ** — การ์ดประเทศ/เมืองไม่มีสมาชิกให้ใส่
   *    บังคับเมื่อไหร่ = ต้องเติมของปลอม ซึ่งเป็นสิ่งที่เปลือกนี้ปฏิเสธมาตั้งแต่ต้น
   * ⚠️ **สิ่งที่ใส่ต้องกว้างคงที่และแคบ** — มันแย่งที่กับชื่อโดยตรง · ชื่อ `truncate` จะสั้นลงตามที่ใส่
   *    ⇒ เหมาะกับ avatar/ตัวเลข **ไม่เหมาะกับข้อความยาว**
   */
  titleTrailing?: ReactNode;
  titleClassName?: string;
  children?: ReactNode;
}) {
  const shell =
    "group relative flex flex-col overflow-hidden rounded-2xl border border-line bg-surface-raised text-left transition hover:border-maple/40 hover:shadow-md hover:shadow-ink/5";

  const body = (
    <>
      <div className="shrink-0">{cover}</div>
      {badge}
      <div className="min-w-0 flex-1 p-3">
        {/* 🔴 **ไม่เผื่อที่ขวาให้ป้ายแล้ว** — ป้ายอยู่มุมขวาบนของ *รูป* ซึ่งตอนนี้อยู่เหนือชื่อเสมอ
            ⇒ ไม่มีการทับกันให้ต้องเผื่อ · เผื่อไว้เฉย ๆ = ชื่อถูกตัดสั้นลงโดยไม่มีเหตุผล
            · `min-w-0` บนชื่อ = ตัวที่ทำให้ `truncate` ทำงานในแถว flex (ไม่มีแล้วมันจะดันของข้างขวาหลุดขอบ) */}
        <div className="flex items-center gap-2">
          <h3 className={`min-w-0 flex-1 truncate text-content ${titleClassName}`}>{title}</h3>
          {/* 🔴 `pointer-events-auto` — ของในช่องนี้ *กดได้* ทั้งที่ทั้งการ์ดเป็นลิงก์ (ดูคำอธิบายข้างล่าง) */}
          {titleTrailing && <div className="pointer-events-auto shrink-0">{titleTrailing}</div>}
        </div>
        {children}
      </div>
    </>
  );

  /**
   * 🔴 **การ์ดที่เป็นลิงก์ ใช้ท่า "ลิงก์คลุมทั้งใบ" ไม่ใช่ `<Link>` ห่อเนื้อ** (P2 · 4 ก.ย. 2026)
   *
   * เหตุผลเดียว: ***`<button>` ซ้อนใน `<a>` เป็น HTML ที่ผิด*** — เบราว์เซอร์จะ *ยกปุ่มออกมานอกลิงก์เอง*
   * ตอน parse ⇒ ตำแหน่งเพี้ยนแบบที่ไม่มีอะไรฟ้อง · และผู้ใช้ขอให้ **กดที่แถวสมาชิกแล้วเปิดรายชื่อได้**
   * ⇒ ต้องมีปุ่มจริงอยู่ในการ์ดที่เป็นลิงก์
   *
   * ## ท่าที่ใช้ — `<Link>` เป็นแผ่นใสคลุมทั้งใบ อยู่ *ใต้* เนื้อ
   * ```
   * <div relative>            เปลือก
   *   <Link absolute inset-0> แผ่นใสกินพื้นที่ทั้งใบ ← สิ่งที่ถูกกดตอนกดที่ว่าง ๆ
   *   <div pointer-events-none> เนื้อ ปล่อยคลิกทะลุลงไปหาลิงก์
   *     …<div pointer-events-auto> ของที่กดได้เอง ← ชนะเพราะอยู่บนสุด
   * ```
   * ⚠️ **ราคาที่จ่าย: เลือกข้อความในการ์ดด้วยเมาส์ไม่ได้** (`pointer-events-none` ปิดไปด้วย)
   *    ยอมได้เพราะการ์ดเป็น *ปุ่มนำทาง* ไม่ใช่ *เนื้อความให้อ่านแล้วก๊อป*
   * 🔴 **`aria-label` บนลิงก์ต้องมี** — ลิงก์นี้ไม่มีข้อความข้างในเลย (เนื้ออยู่นอกมัน)
   *    ⇒ ไม่ใส่ = โปรแกรมอ่านหน้าจอประกาศว่า "ลิงก์" เฉย ๆ **ไม่บอกว่าไปไหน**
   */
  if (href) {
    return (
      <div className={shell}>
        <Link
          href={href}
          aria-label={typeof title === "string" ? title : undefined}
          className="absolute inset-0 z-0"
        />
        <div className="pointer-events-none relative z-10 flex flex-1 flex-col">{body}</div>
      </div>
    );
  }
  if (!onClick) {
    return <div className={shell}>{body}</div>;
  }
  return (
    <button type="button" onClick={onClick} className={shell}>
      {body}
    </button>
  );
}

/**
 * ป้ายมุมขวาบนของ `CoverCard` — **รูปเดียว ตำแหน่งเดียว ทุกชนิดการ์ด**
 * 🔴 คู่สีต้องผ่าน WCAG AA เพราะเป็น `text-2xs` = ข้อความปกติ (วัดแล้ว: `maple`/white = 3.50 ❌
 * · `maple-dark`/white = 4.98 ✅ · `pine`/cream = 7.61 ✅ · `ink`/cream = 14.23 ✅)
 */
export function CardBadge({ tone, children }: { tone: string; children: ReactNode }) {
  return (
    <span
      className={`absolute right-2 top-2 rounded-full px-2.5 py-1 text-2xs font-semibold shadow-sm shadow-ink/20 ${tone}`}
    >
      {children}
    </span>
  );
}
