function CountryThumb({ countryId }: { countryId: string }) {
  /**
   * 🔴 **`useState` สองตัว ไม่ใช่ตัวเดียวที่นับเลข** — แต่ละชั้นต้องจำ *ของตัวเอง* ว่าเจ๊งไปแล้ว
   * ถ้าใช้ตัวนับรวม จะแยกไม่ออกว่า "ภาพจริงไม่มี" กับ "SVG ไม่มี" ⇒ เดาลำดับผิดเมื่อชั้นใดชั้นหนึ่งหายทีหลัง
   * · 🔴 **`key` บน `<img>` จำเป็น** — ไม่มีมัน React จะ reuse โหนดเดิมตอนสลับ `src`
   *   แล้ว `onError` ของภาพเก่าอาจยิงทับสถานะของภาพใหม่ (เจอรูปนี้มาแล้วกับ `CoverCard`)
   */
  const [photoBroken, setPhotoBroken] = useState(false);
  const [svgBroken, setSvgBroken] = useState(false);

  if (!photoBroken) {
    return (
      // eslint-disable-next-line @next/next/no-img-element -- ไฟล์ static ใน public/catalog/ ที่ทีมวางเอง
      <img
        key={`photo-${countryId}`}
        src={`/catalog/${countryId}/${countryId}.jpg`}
        alt=""
        className="aspect-video w-full object-cover"
        onError={() => setPhotoBroken(true)}
      />
    );
  }

  const broken = svgBroken;
  if (broken) {
    /**
     * 🔴 **พื้นไล่สีเปล่า ไม่ใส่ธงซ้ำ** — ธงอยู่ในบรรทัดชื่อแล้ว **ทุกใบ**
     * ยิงจริงตอนใส่ทั้งสองที่: ประเทศที่ไม่มีไฟล์รูปได้ `🇨🇳 🇨🇳จีน` **ธงซ้ำสองรอบ**
     * ส่วนสี่ประเทศที่มีไฟล์รูปได้ธงรอบเดียว ⇒ **การ์ดเก้าใบมีสองแบบโดยไม่ได้ตั้งใจ**
     * 🎯 ***ไอคอนต้องอยู่ที่เดียว "ที่มีเสมอ" ไม่ใช่สองที่ "ที่มีบ้างไม่มีบ้าง"***
     */
    return <div className="aspect-video w-full bg-gradient-to-br from-pine to-maple" />;
  }
  return (
    // eslint-disable-next-line @next/next/no-img-element -- ไฟล์ static ใน public/covers/ ที่ทีมวางเอง
    <img
      key={`svg-${countryId}`}
      src={`/covers/country-${countryId}.svg`}
      alt=""
      className="aspect-video w-full object-cover"
      onError={() => setSvgBroken(true)}
    />
  );
}

