"use client";

/**
 * แทนที่**เฉพาะโครงวันที่มาจาก `ITINERARY`** (dates/cities/weather + `useStops`/`useDaySettings`/
 * `useOvernightOverrides`) เมื่อ `useTripDaysGate` ยืนยันว่าทริปนี้ `trip_days` ว่างเปล่า
 *
 * 🔴 **ไม่ใช่ full-page fallback อีกต่อไป** (เคยเป็นแบบนั้นใน `08c591c` — ย้ายออกจาก `TripDataProvider`
 * แล้วเพราะที่พัก/booking/สถานที่ที่เพิ่มเองไม่ได้พึ่ง `trip_days` เลย บล็อกทั้งหน้าจึงกินของถูกไปด้วย)
 * (P1/P3, 27 ส.ค. 2026) ตอนนี้ผู้ใช้ยังเห็นที่พัก/booking ของตัวเองตามปกติ เห็นแค่ส่วนแผนรายวันที่บอกตรง ๆ
 * ว่ายังแสดงไม่ได้ — หน้าจอที่จริงบางส่วน ดีกว่าหน้าจอว่างทั้งหน้า และดีกว่าของเดิม (เต็มหน้าแต่เป็นทริปอื่น)
 *
 * 🔴 **ข้อความต้องไม่อ่านเหมือนบั๊ก** (P1) — ผู้ใช้ที่เพิ่งสร้างทริปเองไม่ได้ทำอะไรผิด
 *
 * 🔴 **แก้ 27 ส.ค. 2026 (P1) — บรรทัดที่สองเคยอ้าง "ที่พัก/ตั๋วของคุณยังอยู่ครบตามปกติ"** ซึ่งเป็นการอ้าง
 * *สถานะข้อมูลของผู้ใช้* จากหน้าที่บล็อกอยู่ — ตรวจสอบไม่ได้จากตรงนี้เลย และผิดทันทีที่ทริปนั้นไม่มีที่พัก/ตั๋ว
 * จริง (ยืนยันด้วยทริปทดสอบ `e52b7d72` — 0 hotels/bookings/checklist ทุกตาราง) เปลี่ยนเป็นข้อความที่อธิบาย
 * *กฎ* (ส่วนไหนยังใช้งานได้) แทนการอ้าง *ข้อมูลของเขา* — ตระกูลเดียวกับ `D71`
 */
/**
 * 🔴 **สองเหตุ ต้องมีข้อความคนละอัน — ห้ามยุบ** (P2 · 28 ส.ค. 2026 · P7 เจอเคส `unreadable`)
 * · `no-days`    — ถามฐานได้ และฐานตอบว่า **ทริปนี้ไม่มีวัน** · เป็นสถานะของ *ข้อมูล*
 * · `unreadable` — **ถามไม่ได้** (ออฟไลน์/เน็ตสะดุด) · เป็นสถานะของ *การเชื่อมต่อ*
 * 🎯 ผู้ใช้ทำคนละอย่างกัน: อันแรกรอระบบ · อันหลัง **ต่อเน็ตแล้วลองใหม่ได้เอง**
 *    ยุบเป็นข้อความเดียว = บอกคนที่แค่เน็ตหลุดว่า "ระบบยังไม่รองรับ" ซึ่งผิดและเขาจะเลิกลอง
 */
export type DayPlanUnavailableReason = "no-days" | "unreadable";

export function DayPlanUnavailableNotice({
  reason = "no-days",
}: {
  reason?: DayPlanUnavailableReason;
}) {
  const copy =
    reason === "unreadable"
      ? {
          // 🔴 ไม่เขียนว่า "คุณออฟไลน์" — ตรวจจากตรงนี้ไม่ได้ · `navigator.onLine` โกหกเป็นประจำ
          //    (เชื่อมต่อ Wi-Fi ที่ไม่มีเน็ตก็ยังรายงาน `true`) · บอก *สิ่งที่เรารู้* คือคำขอไม่สำเร็จ
          head: "ยังโหลดแผนรายวันไม่ได้ — ติดต่อเซิร์ฟเวอร์ไม่สำเร็จ",
          sub: "ถ้าเน็ตกลับมาแล้ว ลองเปิดหน้านี้ใหม่อีกครั้ง",
        }
      : {
          head: "แผนรายวันของทริปนี้ยังแสดงไม่ได้ — ระบบกำลังรองรับทริปหลายใบอยู่",
          sub: "ส่วนที่ไม่เกี่ยวกับแผนรายวัน (ที่พัก/ตั๋ว/ของที่ต้องเตรียม) ยังใช้งานได้ตามปกติ",
        };

  return (
    <div className="flex flex-col items-center gap-1 rounded-2xl bg-surface-soft p-6 text-center">
      <p className="text-content">{copy.head}</p>
      <p className="text-sm text-content-soft">{copy.sub}</p>
    </div>
  );
}
