#!/bin/bash
# บันทึกภาพปกเมือง/ประเทศ — ย่อ + ตั้งชื่อ + เก็บเข้าโฟลเดอร์ประเทศ
#   ใช้:  ./scripts/save-cover.sh <ไฟล์ต้นทาง> <country_id> <ชื่อเมืองหรือประเทศ>
#   เช่น: ./scripts/save-cover.sh ~/Downloads/Gemini_xxx.jpeg kr gyeongju
#
# 🔴 ย่อเหลือกว้าง **800px** เสมอ (เดิม 1200 — เปลี่ยน 6 ก.ย. 2026 หลังวัดกล่องจริง ดูเหตุผลด้านล่าง)
#    ต้นฉบับจาก Gemini ~3584px/~4.4MB ต่อใบ ⇒ ทั้งคลังจะเป็นหลายร้อย MB · ที่ 800px คลัง 73 ใบ = **9.2MB**
# ⚠️ sips บนเครื่องนี้ **แปลง webp ไม่ได้** (exit 13) จึงเก็บเป็น .jpg
#
# 🔴 **ลำดับที่ถูกคือ *ดูภาพต้นทางก่อน* แล้วค่อยเรียกสคริปต์นี้** (P4 เสนอ · รับ · 5 ก.ย. 2026)
#    ฉบับแรกบอกให้ดู *หลัง* เก็บ ⇒ ถ้าหยิบผิดไฟล์ **มันถูกเขียนทับใต้ชื่อเมืองไปแล้ว ต้องไล่ย้อน**
#    🎯 ***ตรวจก่อนเขียน = ไม่มีอะไรต้องแก้ · ตรวจหลังเขียน = มีของผิดอยู่ในระบบชั่วขณะหนึ่งเสมอ***
#    (บรรทัดเตือนท้ายสคริปต์ยังอยู่ในฐานะ *ตาข่ายชั้นสอง* ไม่ใช่ชั้นแรก)
#
# 🔴 **ห้ามใช้ "ไฟล์ใหม่สุดใน Downloads" เป็นตัวเลือกอัตโนมัติ**
#    หลายเซสชันโหลดลงโฟลเดอร์เดียวกันพร้อมกัน ⇒ "ใหม่สุด" ของคุณอาจเป็นของคนอื่น
#    และภาพจะถูกเก็บใต้ชื่อเมืองที่ผิด **โดยไม่มีอะไรฟ้อง**
#    ⇒ ระบุพาธเต็มที่คุณเห็นกับตาเสมอ
#    📌 วัดจริง (P4 · 5 ก.ย.): หน้าต่างระหว่าง *กดโหลด* กับ *ไฟล์ลงจริง* กว้าง **18 วินาที**
#       ⇒ "ใหม่สุด ณ ตอนเช็ค" ไม่ได้แค่ *อาจ* ผิด — **มันผิดแน่นอนถ้าเช็คเร็วไป**
set -e
SRC="$1"; COUNTRY="$2"; NAME="$3"
[ -n "$SRC" ] && [ -n "$COUNTRY" ] && [ -n "$NAME" ] || { echo "ใช้: $0 <src> <country_id> <name>"; exit 2; }
[ -f "$SRC" ] || { echo "🔴 ไม่มีไฟล์: $SRC"; exit 1; }
DIR="$(cd "$(dirname "$0")/.." && pwd)/public/catalog/$COUNTRY"
mkdir -p "$DIR"
OUT="$DIR/$NAME.jpg"
# 🔴 **ปฏิเสธ ไม่ใช่เตือน** — คำเตือนที่ไม่หยุดอะไร ถูกกลืนได้ด้วย `| head -1` (P5 ทับของ P2 มาแล้ว 5 ก.ย.)
#    ทรีเป็นของกลาง ⇒ ไฟล์ที่ "ยังไม่มี" ตอนคุณเช็ค มีได้แล้วตอนคุณเซฟ (ห่างกัน 1 นาทีจริง)
if [ -f "$OUT" ] && [ "${3:-}" != "--force" ] && [ "${4:-}" != "--force" ]; then
  echo "🔴 มีไฟล์อยู่แล้ว: $COUNTRY/$NAME.jpg — ไม่เขียนทับ" >&2
  echo "   ถ้าตั้งใจจะแทนที่ของคนอื่นจริง ให้คุยกับเจ้าของก่อน แล้วต่อท้ายด้วย --force" >&2
  exit 1
fi
AGE=$(( $(date +%s) - $(stat -f%m "$SRC") ))
[ "$AGE" -lt 300 ] || echo "⚠️  ไฟล์ต้นทางเก่า ${AGE}s — แน่ใจว่าเป็นใบที่เพิ่งเจนใช่ไหม"
# 🔴 **ย่อเท่านั้น ไม่ขยาย** — `sips -Z` ขยายภาพที่เล็กกว่าเป้าด้วย
#    วิธี "ดาวน์โหลดโดยตั้งชื่อเอง" ได้ภาพจาก DOM ซึ่งกว้าง **1024** ไม่ใช่ 3584
#    ⇒ อัปสเกลแล้วเบลอโดยไม่ได้อะไรกลับมา
# 🔴 **เพดาน 800 มาจากการวัดกล่องจริง ไม่ใช่ตัวเลขกลม ๆ** (6 ก.ย. 2026 · ยิง /explore/jp สองขนาด)
#    มือถือ 375px  กล่อง 164 CSS x DPR 2 = **328px**
#    เดสก์ท็อป 1440 กล่อง 278 CSS x DPR 2 (retina) = **556px**  ← เคสหนักสุด
#    ⇒ 800 คลุมทั้งคู่ + เหลือเผื่อ · 1200 เดิม = จ่ายค่าขนส่งเกินราว 2.2 เท่า (คลัง 16.7MB → 9.2MB)
#    ⚠️ ก่อนหน้านี้ทีมคิดเลขนี้ผิดกันสามคนคนละทิศ เพราะเทียบ "px ของ CSS" กับ "px ของไฟล์" ตรง ๆ โดยไม่คูณ DPR
SRCW=$(sips -g pixelWidth "$SRC" | awk '/pixelWidth/{print $2}')
if [ "${SRCW:-0}" -gt 800 ]; then
  sips -Z 800 "$SRC" --out "$OUT" >/dev/null
else
  cp "$SRC" "$OUT"
fi
W=$(sips -g pixelWidth "$OUT" | awk '/pixelWidth/{print $2}')
H=$(sips -g pixelHeight "$OUT" | awk '/pixelHeight/{print $2}')
SZ=$(stat -f%z "$OUT")

# 🔴 **ปฏิเสธ ไม่ใช่แค่เตือน** — การ์ดทั้งเว็บเป็น `aspect-video` (16:9) ตั้งแต่ `ddf6c9c`
#    ⇒ ภาพที่ทรงไม่ตรงจะถูก `object-cover` ครอปทิ้งเงียบ ๆ
#    วัดจริง 5 ก.ย.: `--ar 16:9` ของ Gemini คืน **1.794–1.835** (ห่าง 16:9 ไม่เกิน 3% ⇒ รับได้)
#    แต่พรอมป์ที่ขอ 3:1 คืน **3.030** ⇒ ครอปหาย **41%** — คยองจูเหลือแต่แถบกลาง
# 🎯 ***เดิมสคริปต์ "พิมพ์ ${W}x${H} ออกจอ" ทุกรอบ แล้วไม่มีใครอ่าน — ตัวเลขที่พิมพ์โดยไม่มีเกณฑ์ คือ log ไม่ใช่การวัด*** (P1 ชี้)
# 🔴 **ไม่ครอปให้อัตโนมัติ** — ครอปเองจะตัดยอดเจดีย์/ยอดเขาทิ้งโดยไม่มีใครรู้
#    **คนที่รู้ว่าอะไรสำคัญในภาพ คือคนที่เจนมัน ไม่ใช่สคริปต์** (P1 เสนอ · รับ)
if ! python3 -c "import sys; sys.exit(0 if abs($W/$H - 16/9) < 0.08 else 1)"; then
  R=$(python3 -c "print(round($W/$H,3))")
  rm -f "$OUT"
  echo "🔴 ทรงไม่ใช่ 16:9 — ${W}x${H} (ratio $R · ต้องการ ~1.778)"
  echo "   ลบไฟล์ปลายทางแล้ว · เจนใหม่โดยใส่ --ar 16:9 ในพรอมป์"
  exit 1
fi
echo "✅ $COUNTRY/$NAME.jpg  ${W}x${H}  $((SZ/1024))KB  ratio $(python3 -c "print(round($W/$H,3))")"
echo "🔴 ขั้นต่อไป: เปิดดูภาพนี้ด้วยตา (Read $OUT) ว่าเป็นเมืองนั้นจริง ก่อน commit"
