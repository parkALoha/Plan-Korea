/**
 * เส้นทางที่ต้องเข้าได้เสมอ
 * - 🔴 `/login`, `/auth/callback` — **ไก่กับไข่**: ถ้าด่านดัก 2 เส้นนี้ จะล็อกอินไม่ได้เลยตลอดกาล
 *   เพราะทางเข้าถูกด่านที่รอทางเข้าปิดอยู่ (เหตุผลเดียวกับที่ `/unlock` เคยต้องอยู่ในลิสต์นี้)
 * - `/sw.js`, `/manifest.webmanifest` — เบราว์เซอร์ขอ 2 ไฟล์นี้แบบ **ไม่แนบคุกกี้**
 *   ถ้าโดนด่านดักจะได้ 307 ไปหน้า HTML แทนไฟล์จริง → ลงทะเบียน service worker ไม่ผ่าน
 *   และปุ่ม "เพิ่มลงหน้าจอโฮม" ไม่ขึ้น · ทั้งสองไฟล์ไม่มีข้อมูลผู้ใช้อยู่ข้างใน จึงเปิดสาธารณะได้
 * - `/api/keep-alive` — Vercel Cron ยิงมาโดยไม่มีคุกกี้ · route นั้นมีด่าน `CRON_SECRET` ของตัวเอง
 *   และไม่คืนข้อมูลออกมาเลย (ตอบแค่ ok/เวลา)
 *
 * ## 🔴 เพิ่ม 4 ก.ย. 2026 — เส้นทาง "เปิดดูก่อนสมัคร" (ผู้ใช้สั่ง · P1 เขียน · **โซน P4 ขอให้ตรวจ**)
 * ผู้ใช้สั่งว่า *"คนที่ไม่ได้ล็อกอิน ควรจะเข้าหน้าแรกได้ … ดูทริปแนะนำได้ แต่สร้างทริปไม่ได้"*
 *
 * 🎯 ***แก้ route อย่างเดียวไม่เปิดอะไรเลย — ด่านนี้ดักก่อนถึง route ทุกใบ***
 *    (ผมยิง RPC ในฐานได้ `200` แล้วเกือบสรุปว่าฟีเจอร์พร้อม · ยิงผ่านเว็บจริงได้ `401`
 *     รูปเดียวกับ `§3.5` *"มีสิทธิ์ ≠ เรียกได้ — ยืนยันด้วยเส้นทางที่ผู้เรียกจริงใช้"* แค่คนละชั้น)
 *
 * **สามเส้น API ที่เปิด — ทั้งสามอ่านอย่างเดียวและไม่มีข้อมูลผู้ใช้เลยสักไบต์:**
 * · `/api/engine/countries`      → `list_public_destinations()` (definer · คลังสาธารณะ)
 * · `/api/engine/cities`         → **เปิดเฉพาะกิ่ง `?country=xx`** · กิ่ง `q` ยัง `401` ในตัว route เอง
 * · `/api/engine/trip-templates` → ทริปที่ติดธง `published_template_at` เท่านั้น
 * 🔴 **ทั้งสามไม่มี `grant` บนตารางใดให้ `anon`** — ข้อมูลออกทาง RPC `security definer` เท่านั้น
 *    ⇒ **ด่านนี้เปิดแค่ *ทางเดิน* ไม่ได้เปิด *ตาราง*** · เผลอเพิ่มเส้นที่ `select` ตรงเข้าลิสต์นี้เมื่อไหร่
 *      ความจริงข้อนั้นหายทันที · **เส้นใหม่ทุกเส้นต้องตอบให้ได้ว่า "ข้อมูลออกทางไหน"**
 *
 * ## ⚠️ ข้อแลกที่คอมเมนต์ข้างล่างเตือนไว้เอง และผมยอมรับมันโดยรู้ตัว
 * ด่านนี้เป็น **fail-closed โดยตั้งใจ** — *"ตั้งค่าผิด → ไม่มี user → เด้ง `/login` ซึ่งบอกความจริง
 * มากกว่าหน้าเปล่า"* · การเปิด `/` ทำให้สภาพ *"ตั้งค่าผิด"* ไม่เด้งไปหน้าที่บอกความจริงอีกต่อไป
 * · ✅ **แต่มันไม่เงียบ**: หน้าแรกดึงข้อมูลผ่านสามเส้นบน ซึ่งตอบ `502` เมื่อ Supabase ใช้ไม่ได้
 *   ⇒ ได้ *หน้าที่มีข้อความผิดพลาด* ไม่ใช่ *หน้าเปล่า* — ซึ่งเป็นสิ่งที่คอมเมนต์นั้นกลัวจริง ๆ
 * · 🔴 **ถ้าวันหนึ่งหน้าแรกเลิกยิงสามเส้นนี้ตอนโหลด ข้อแลกนี้จะเปลี่ยนกลับเป็นเงียบทันที**
 *   และ **ไม่มีอะไรในไฟล์นี้จะรู้** — ผูกไว้กับเคสใน `proxy.test.ts` ไม่ใช่กับคอมเมนต์นี้
 */
