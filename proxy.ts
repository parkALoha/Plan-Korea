export async function proxy(req: NextRequest) {
  const { pathname } = req.nextUrl;

  // 🔴 ต่ออายุ session **ก่อนด่านใด ๆ และก่อนการคืนค่าทุกทาง** (E1)
  // ถ้าวางไว้หลังด่าน PIN เส้นทางที่ปล่อยผ่านตั้งแต่ต้น (เช่น `/login`) จะไม่ถูกต่ออายุเลย
  // → ผู้ใช้ที่ค้างอยู่หน้านั้นนาน ๆ จะหลุดทั้งที่ไม่ได้ทำอะไรผิด
  // ⚠️ ต้องคืน `session.response` เสมอเมื่อจะปล่อยผ่าน **ห้ามสร้าง `NextResponse.next()` ใหม่**
  //    ไม่งั้นคุกกี้ที่เพิ่งต่ออายุจะหายไปเงียบ ๆ และอาการจะโผล่ตอน token เดิมหมดอายุเท่านั้น
  const session = await refreshSession(req);

  if (
    PUBLIC_EXACT_PATHS.includes(pathname) ||
    PUBLIC_SUBTREE_PATHS.some((p) => pathname === p || pathname.startsWith(`${p}/`))
  ) {
    return session.response;
  }

  // 🔴 **กลับทิศจากด่าน PIN โดยตั้งใจ — ด่านเดิม fail-open ด่านนี้ fail-closed**
  //
  // ด่าน PIN เลือกปล่อยผ่านตอน env ไม่ครบ เพราะ *"ลืมตั้ง env บน Vercel แล้วเว็บตายทั้งเว็บ
  // อันตรายกว่า ตอนอยู่เกาหลีจริงแล้วเปิด /today ไม่ได้"* — **เหตุผลนั้นถูกสำหรับเว็บทริป**
  // เพราะข้อมูลทริปอยู่ในโค้ดและ IndexedDB แอปยังทำงานได้โดยไม่มี Supabase
  //
  // ⚠️ **แพลตฟอร์มไม่ใช่แบบนั้น**: ตาราง · RLS · ตัวตน อยู่ใน Supabase ทั้งหมด
  // ไม่มี Supabase = **ไม่มีข้อมูลให้แสดงอยู่แล้ว** → ปล่อยผ่านไม่ได้อะไรกลับมาเลย
  // ได้แค่หน้าเปล่าที่ไม่มีด่าน ซึ่งเป็นสภาพที่คนตั้งค่าผิดจะไม่มีทางสังเกตเห็น
  // → **ไม่มี user = ไม่ผ่าน** ทั้งกรณี "ยังไม่ล็อกอิน" และกรณี "ยังไม่ได้ตั้งค่า"
  //   สองกรณีนี้จบที่หน้า `/login` เหมือนกัน ซึ่งบอกความจริงกับผู้ใช้มากกว่าหน้าเปล่า
  if (session.user) {
    return session.response;
  }

  // 🔴 **หน้าแรกเปิดให้คนยังไม่ล็อกอิน — แต่ *เฉพาะ `/` เป๊ะ ๆ*** (ผู้ใช้สั่ง 4 ก.ย. 2026)
  //    ⚠️ `/trip/...` · `/account` · `/today` · `/summary` **ยังเด้ง `/login` เหมือนเดิมทุกเส้น**
  //
  // 📌 **ทำไมอยู่ตรงนี้ ไม่ใช่ใน `PUBLIC_SUBTREE_PATHS` — เหตุผลที่ผมเขียนไว้รอบแรก *ผิด* จึงเขียนใหม่**
  //    ฉบับแรกอ้างว่า `"/"` ในลิสต์จะกลายเป็น prefix ของทุก path · **ไม่จริง** —
  //    ตัวจับสร้าง `` `${p}/` `` ⇒ ได้ `"//"` ซึ่งไม่มี path ไหน `startsWith` ⇒ **ใส่ไปก็ไม่มีผลอะไรเลย**
  //    🔴 จับได้ด้วยการยิงมัลแตนต์ (ใส่ `"/"` เข้าลิสต์ → **ไม่มีเคสไหนแดงสักใบ**) ไม่ใช่ด้วยการอ่าน
  //    🎯 ***คำอธิบายที่ฟังขึ้นและผิด อันตรายกว่าไม่มีคำอธิบาย — คนอ่านจะเลิกถามต่อ***
  //
  //    **เหตุผลจริงที่ยังคุ้มจะแยกไว้ที่นี่:** อันตรายจริงคือ ***ลิสต์กับตัวจับหลวมพร้อมกัน***
  //    (มัลแตนต์ที่เปลี่ยนตัวจับเป็น `startsWith(p)` **พร้อม** `"/"` ในลิสต์ → เคสแดง 15 ใบ)
  //    ⇒ `/` ไม่อยู่ในลิสต์ = **ถอดตัวประกอบหนึ่งตัวออกจากคู่ที่ต้องมาด้วยกันถึงจะพัง**
  //    · และเทียบตรง ๆ ที่นี่ **greppable** กว่า — คนหา "ทำไมหน้าแรกเปิด" เจอบรรทัดนี้ ไม่ใช่สตริงในอาเรย์
  if (pathname === "/") {
    return session.response;
  }

  // 🔴 **`/explore` เปิดให้คนยังไม่ล็อกอิน — ผู้ใช้สั่งเอง 5 ก.ย. 2026 หลังเจอกับตัว**
  //    (*"คนไม่ login เปิดแล้วติดนะ พอเปิดแล้วไปที่ `/login?next=%2Fexplore`"*)
  //
  // 🎯 ***ก่อนหน้านี้ API ถูกเปิดให้ `anon` แล้ว แต่หน้าที่ใช้มันยังปิด ⇒ `/api/engine/cities`
  //    สาธารณะที่สร้างไว้ **ไม่มีเส้นทางไหนเรียกถึงได้เลยสักครั้ง*** — P1 เป็นคนสร้างทั้งสองฝั่งและปิดข้างเดียว
  //    · หน้าแรกโชว์การ์ดประเทศให้คนแปลกหน้า แล้วกดปุ๊บเจอกำแพงล็อกอิน = flow ตายในคลิกเดียว
  //
  // 📌 **ทำไมเทียบตรงที่นี่ ไม่ใช่ใส่ `PUBLIC_SUBTREE_PATHS`** — เหตุผลเดียวกับ `"/"` ข้างบน:
  //    อันตรายจริงคือ *ลิสต์กับตัวจับหลวมพร้อมกัน* ⇒ ไม่เพิ่มสมาชิกในลิสต์ถ้าไม่จำเป็น
  //
  // ⚠️ **สิ่งที่ทำให้ปลอดภัย ไม่ได้อยู่ในบรรทัดนี้ — มันอยู่ที่หน้าไม่มีเส้นทางไปถึงข้อมูลผู้ใช้**
  //    ***ทุกไฟล์ใต้ `app/` ที่ไม่ได้อยู่ใน `app/api/` ห้ามเชื่อมถึง DAL (`lib/engine/db.ts`)***
  //    บังคับด้วย `lib/__tests__/serverDataReach.test.ts` (`outsideApi` — ไม่มีคำว่า `explore` ในไฟล์นั้นเลย)
  //    🔴 **ฉบับก่อนหน้าเขียนว่า `app/explore/**` ซึ่ง *แคบกว่าด่านจริง*** (P3 จับ 5 ก.ย. 2026)
  //       ทิศนี้ไม่ได้สัญญาเกิน มัน **สัญญาขาด** ⇒ คนอ่านคิดว่ามี *ทะเบียนโฟลเดอร์ที่ถูกเฝ้า* ซึ่งไม่มีอยู่จริง
  //       แล้วไปสร้างงานซ้ำ · 📌 เกิดจริง: P3 เกือบตอบ P2 ว่าหน้าใหม่ `app/templates/**` ต้องไปเติมเข้าด่าน
  //       **ทั้งที่มันถูกครอบตั้งแต่วินาทีที่สร้างโฟลเดอร์**
  //    ✅ ผูกกับ *กลไก* ไม่ใช่ *รายชื่อ* ⇒ โฟลเดอร์ใหม่ถูกครอบเองโดยไม่ต้องมีใครมาแก้บรรทัดนี้
  //    🔴 **วันที่ด่านนั้นถูกถอด บรรทัดนี้จะกลายเป็นช่องทันที และไม่มีอะไรตรงนี้ส่งเสียง**
  //
  // 🔴 `startsWith("/explore/")` ครอบ path ที่ลึกกว่าหนึ่งชั้นด้วย — วันนี้มีแค่ `[countryId]`
  //    รหัสประเทศถูก validate ในหน้า (`COUNTRY_ID`) ⇒ ค่ามั่วได้หน้าว่าง ไม่ใช่ข้อมูลใคร
  if (pathname === "/explore" || pathname.startsWith("/explore/")) {
    return session.response;
  }

  // API ตอบ 401 เป็น JSON ไม่ redirect — ฝั่ง client เป็น fetch การ redirect ไปหน้า HTML
  // จะทำให้ได้ response ที่ parse ไม่ออกแทนที่จะรู้ชัดๆ ว่ายังไม่ได้ล็อกอิน
  // 🔴 `S5`: ถูกบล็อกไม่ได้แปลว่าทิ้งคุกกี้ที่หมุนไปแล้ว — `refreshSession()` รันไปก่อนแล้ว
  //    ถ้าไม่ก็อปมา ไคลเอนต์จะถือ token เก่าที่อาจถูกเพิกถอนแล้ว (เหตุผลเต็มใน proxySession.ts)
  if (pathname.startsWith("/api/")) {
    return withSessionCookies(
      session.response,
      NextResponse.json({ error: "unauthenticated" }, { status: 401 }),
    );
  }

  const url = req.nextUrl.clone();
  url.pathname = "/login";
  // จำหน้าที่ตั้งใจจะเข้าไว้ เพื่อพากลับไปหลังล็อกอิน (เช่นเปิดลิงก์ที่ถูกแชร์มาตรงๆ)
  // `safeNextPath` ฝั่ง callback เป็นคนตรวจค่านี้ก่อนใช้ — ที่นี่เป็นฝั่งเขียน ไม่ใช่ฝั่งเชื่อ
  url.searchParams.set("next", pathname + req.nextUrl.search);
  return withSessionCookies(session.response, NextResponse.redirect(url));
}

