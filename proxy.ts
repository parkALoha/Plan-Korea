  "/sw.js",
  "/manifest.webmanifest",
  "/api/keep-alive",
  "/login",
  "/auth/callback",
  // ── เปิดดูก่อนสมัคร (อ่านอย่างเดียว · ไม่มีข้อมูลผู้ใช้) ──
  "/api/engine/countries",
