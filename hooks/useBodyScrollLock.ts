"use client";

import { useEffect } from "react";

/**
 * ล็อกไม่ให้หน้าเว็บข้างหลังเลื่อนตอนเปิดชั้นซ้อน (modal · lightbox · sidebar)
 *
 * ## 🔴 นับจำนวนผู้ถือ ไม่ใช่ save/restore ต่อคน (5 ก.ย. 2026 · P4 สังเกต · P7 ไล่ · P2 ตัดสินและแก้)
 * ฉบับเดิมเก็บ `original` **ของใครของมัน** แล้วคืนค่าตอน unmount
 * ⇒ ถูกต่อเมื่อ **ตัวในสุดถอนก่อนเสมอ** ซึ่งเป็นจริงวันนี้ *เพราะทุกคู่ที่ซ้อนกันในรีโปเป็นพ่อ–ลูก*
 * ```
 * PlaceDetailModal:218  <PhotoLightbox> อยู่ **ใน** <Modal>   → ลูก
 * PlaceSidebar          เรนเดอร์ <PlaceDetailModal> → <Modal>  → ลูก
 * BookingEditModal:481  <PhotoLightbox> ในตัวมันเอง           → ลูก
 * ```
 * 🎯 ***มันปลอดภัยด้วย *รูปทรงของต้นไม้คอมโพเนนต์* ไม่ใช่ด้วยกลไกของตัวเอง***
 * 🔴 **และวันที่มีคนย้าย `<PhotoLightbox>` ออกมาเป็น *พี่น้อง* ของ `<Modal>` — ซึ่งเป็นรีแฟกเตอร์ที่อ่านแล้วดูดีขึ้น —
 *    ลำดับ unmount ไม่ถูกรับประกันอีกต่อไป ⇒ ตัวนอกถอนก่อนจะ `restore("")` **ทั้งที่ยังมีชั้นเปิดค้างอยู่**
 *    ⇒ หน้าเลื่อนได้ใต้ชั้นที่เปิดอยู่ · **`tsc`/`lint`/เทสต์ ไม่มีตัวไหนส่งเสียง**
 *
 * ## ✅ ตัวนับปิดช่องนั้นโดยไม่ต้องรู้ว่าใครเป็นลูกใคร
 * ```
 * 0 → 1   เก็บค่าเดิมครั้งเดียว แล้วล็อก
 * 1 → 2   ไม่ทำอะไร (ล็อกอยู่แล้ว)
 * 2 → 1   ไม่ทำอะไร — **ยังมีคนถืออยู่**   ← จุดที่ฉบับเดิมปลดล็อกผิดจังหวะได้
 * 1 → 0   คืนค่าเดิมที่เก็บไว้ตอน 0 → 1
 * ```
 * 🎯 ***เปลี่ยนคำถามจาก "ใครถอนก่อน" เป็น "ยังมีใครถืออยู่ไหม" — คำถามที่สองไม่ขึ้นกับลำดับ***
 *
 * ## ⚠️ ขอบเขต — เขียนเพราะข้อจำกัดที่ไม่ได้เขียน จะถูกอ่านว่าไม่มี
 * · ตัวนับเป็น **module-level** ⇒ **หนึ่งตัวนับต่อหนึ่ง JS realm**
 *   ✅ **`iframe`/`window.open` ปลอดภัย เพราะได้ realm แยก ⇒ ได้โมดูลของตัวเอง ⇒ `holders` เริ่มที่ 0 แยกกัน**
 *      (วันนี้มี `<iframe>` 2 ใบ · `window.open` 2 จุด — **ไม่มีใบไหนเข้าเงื่อนไข**)
 *   🔴 ตัวที่พังแคบกว่านั้นมาก: ***realm เดียว เขียน `document.body` มากกว่าหนึ่งใบ*** —
 *      `createPortal(node, otherDoc.body)` จากคอมโพเนนต์ที่เรียกฮุคนี้
 *      · วัดแล้ว: `createPortal` มี 2 จุด (`Modal.tsx` · `AnchoredPanel.tsx`) **ชี้ document หลักทั้งคู่** ⇒ 0 จุดที่เข้าเงื่อนไข
 *   🎯 ***ฉบับแรกของบรรทัดนี้เขียนว่า "iframe/popup จะพัง" ซึ่งกว้างเกินจริง*** (P7 ชี้ · เขาไล่ของจริงมาหักให้)
 *      ⇒ คนถัดไปที่เปิด `GoogleMapEmbed.tsx` แล้วเจอ `<iframe>` **จะสรุปว่าละเมิดไปแล้ว** หรือแย่กว่านั้นคือ *ชินแล้วเลิกอ่าน*
 *      · `§3.4`: **กลไก (และคำเตือน) ที่แดงใส่คนที่ทำถูก จะถูกเลิกเชื่อทั้งใบ**
 * · **P7 ไล่จากจุดเรนเดอร์แบบสถิต ไม่ได้วัดลำดับ unmount ในเบราว์เซอร์** — ตัวนับทำให้คำถามนั้น
 *   *ไม่ต้องตอบอีกต่อไป* ⇒ นั่นคือเหตุผลที่เลือกทางนี้แทนการไปวัดให้ครบ
 */
let holders = 0;
let originalOverflow = "";

export function useBodyScrollLock() {
  useEffect(() => {
    if (holders === 0) {
      originalOverflow = document.body.style.overflow;
      document.body.style.overflow = "hidden";
    }
    holders += 1;
    return () => {
      holders -= 1;
      if (holders === 0) document.body.style.overflow = originalOverflow;
    };
  }, []);
}
