// จุดกึ่งกลางของแต่ละเมือง — เฉลี่ยพิกัดสถานที่ทั้งหมดในเมืองนั้นจาก PLACES สดๆ แทนที่จะฝัง
// พิกัดไว้แยกต่างหาก กันหลุด sync เวลาเพิ่ม/ลบสถานที่ (เหมือน deriveHotelLegs ใน lib/hotelLegs.ts)
// ใช้ bias ผลการค้นหาที่พักให้ใกล้เคียงเมืองที่กำลังเลือกอยู่จริง
export function cityCenter(city: Place["city"]): { lat: number; lng: number } {
  const cityPlaces = PLACES.filter((p) => p.city === city);
  const sum = cityPlaces.reduce(
    (acc, p) => ({ lat: acc.lat + p.lat, lng: acc.lng + p.lng }),
    { lat: 0, lng: 0 }
  );
  return { lat: sum.lat / cityPlaces.length, lng: sum.lng / cityPlaces.length };
}

