-- เฟส 15 — แถว "ไปสนามบิน/สถานี" (kind='transfer') ต่อยอดจาก kind='intercity' ที่มีอยู่แล้ว (migration 0017)
--
-- ต่างจาก 'intercity' ตรงที่แถวนี้ **มี place_id จริง** (สนามบินใน data/transferPoints.ts)
-- เวลาเดินทางจึงมาจาก Routes API ของจริงเหมือนจุดแวะปกติ ไม่ใช่ตัวเลขที่กรอกเดาเอง
--   · dwell_minutes  = เวลาที่ต้องอยู่ที่สนามบินก่อนเครื่องออก (เช็คอิน/ตม./เดินไปเกต) — ใช้คอลัมน์เดิม
--   · คอลัมน์ใหม่ 2 ตัวข้างล่างคือ "สิ่งที่ต้องไปให้ทัน" ซึ่งเดิมระบบไม่รู้เลยจึงเตือนเวลาชนไม่ได้
--
-- kind เป็น text อิสระอยู่แล้ว (ไม่มี CHECK constraint) จึงไม่ต้องแก้อะไรเพิ่มเพื่อรับค่า 'transfer'
alter table public.trip_stops
  -- เวลาที่ต้องไปให้ทัน รูปแบบ "HH:MM" เวลาท้องถิ่นปลายทาง เช่น '10:35' (เวลาบิน VN409)
  add column if not exists transfer_target_time text,
  -- ป้ายกำกับสิ่งที่ต้องไปให้ทัน เช่น 'VN409 อินชอน → โฮจิมินห์' — โชว์ในคำเตือนให้รู้ว่าชนกับอะไร
  add column if not exists transfer_target_label text;
