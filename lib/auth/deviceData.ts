import { clearAllCaches } from "@/lib/localCache";
import { clearAll as clearOfflineStore } from "@/lib/engine/offlineStore";

/**
 * ล้างข้อมูลที่เครื่องนี้เก็บไว้ให้ผู้ใช้คนก่อน — **ที่เก็บทั้งสองใบ ในการเรียกครั้งเดียว**
 * เจ้าของ: P1-Lead · 2 ก.ย. 2026 · `E6-AC7`
 *
 * ## 🔴 ทำไมต้องเป็นฟังก์ชันเดียว ไม่ใช่ "จำให้เรียกสองตัว"
 * ```
 * localStorage   clearAllCaches()      กวาดทุกคีย์ใต้ `trip-cache:` (รวมชื่อพาสปอร์ต)
 * IndexedDB      clearOfflineStore()   กวาดทั้ง object store
 * ```
 * **"จำให้เรียกทั้งคู่" ล้มไปแล้วหนึ่งครั้ง และล้มเงียบ:** `signOut()` เคยเรียกแค่ตัวแรก
 * จนกระทั่ง P7 ชี้ว่าที่เก็บมีสองใบ (28 ส.ค. 2026) · **ตอนนั้นยังไม่กัด เพราะ IndexedDB ยังว่าง**
 * — ถ้าไม่มีใครทัก มันจะเริ่มกัดในวันที่ hook ตัวแรกย้ายข้อมูลเข้าไป **โดยไม่มีอะไรเปลี่ยนในโค้ดล้าง**
 * 🎯 **บั๊กที่เกิดจากการที่ *ของอื่น* เดินหน้า ไม่ใช่จากการที่โค้ดตรงนี้ผิด** — รีวิว diff มองไม่เห็น
 *
 * ## 🔴 และมันล้มเป็นครั้งที่สองแล้ว ที่ *ทางสลับบัญชี* (P3 ชี้ IndexedDB · P1 พบว่าใหญ่กว่านั้น)
 * ```
 * signOut()                    clearAllCaches() + clearOfflineStore()   ← ทั้งสองใบ ทุกคีย์
 * HomeScreen ตอนเจ้าของเปลี่ยน  clearCache(TRIP_LIST_CACHE_KEY)          ← **คีย์เดียว**
 * ```
 * → สลับบัญชีบนเครื่องเดิมโดยไม่กด "ออกจากระบบ" (session หมดอายุ · ล็อกอินคนละแท็บ):
 *   **ชื่อพาสปอร์ต · ที่พัก · ตั๋ว · สถานที่ที่เพิ่มเอง · โน้ต — ของคนก่อนอยู่ครบ**
 * · ⚠️ `components/ImmigrationSheet.tsx:15-17` เขียนอันตรายข้อนี้ไว้เองทุกตัวอักษร
 *   *("คนถัดไปบนเครื่องเดียวกันเปิดหน้า ตม. เห็นชื่อพาสปอร์ตของคนก่อน")* — **แต่เขียนไว้สำหรับเส้นทาง `signOut`**
 * 🎯 **อันตรายเดียวกัน ถูกปิดแค่ประตูเดียวจากสองประตู** และประตูที่เปิดอยู่คือประตูที่ผู้ใช้ *ไม่ได้ตั้งใจเดินผ่าน*
 *
 * ## ⚠️ สิ่งที่ฟังก์ชันนี้ทำไม่ได้ และต้องพูดออกมา
 * มันห้ามใครเรียก `clearAllCaches()` เดี่ยว ๆ ไม่ได้ · **ยังเรียกได้อยู่ และบางที่ก็ควรเรียก**
 * (`sweepLegacyCaches` มีเหตุผลของมันเอง) · 🔴 **นี่คือ *ทางที่ถูก* ไม่ใช่ *ด่าน***
 * ด่านจริงคือ `lib/__tests__/deviceDataClear.test.ts` ที่ยืนยันว่าทั้งสองใบถูกล้าง
 *
 * 🔴 **ลำดับสำคัญ: กวาดก่อนยิงเน็ตเสมอ** — `auth.signOut()` โยนเมื่อออฟไลน์
 * ถ้าล้างทีหลัง การล้างจะไม่เกิดเลย (P2 ชี้ · 28 ส.ค. 2026) · การล้างท้องถิ่นไม่พึ่งเน็ต จึงทำให้สำเร็จก่อนได้เสมอ
 */
export async function clearDeviceData(): Promise<void> {
  // localStorage ก่อน — เป็น sync จึงสำเร็จแน่นอนแม้ IndexedDB จะมีปัญหา
  clearAllCaches();
  await clearOfflineStore();
}
