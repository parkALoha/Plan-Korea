import { clearDeviceData } from "@/lib/auth/deviceData";

/**
 * ตราประทับ "ข้อมูลในเครื่องนี้เป็นของใคร" — `E6-AC14` · P7 ออกแบบ · P1 เขียน · 2 ก.ย. 2026
 *
 * ## 🔴 ทำไมประทับเอง แทนที่จะอ่านตัวตนจากไลบรารี
 * ด่านนี้ต้องตอบได้ **ตอน render (sync)** และ **ตอนออฟไลน์** พร้อมกัน
 * ```
 * useCurrentUser        async + `getUser()` ยิงเน็ต  → ตอบไม่ได้ทั้งสองข้อ
 * ถอดรูปคุกกี้ของ Supabase  sync ✅ ออฟไลน์ ✅          → **แต่ผูกกับรูปภายในของไลบรารี**
 * ประทับเอง              sync ✅ ออฟไลน์ ✅          → ใช้ `onAuthStateChange` ซึ่งเป็น API สาธารณะ
 * ```
 * 🎯 **ตัวตัดสินคือ *ทิศทางของความล้มเหลว* ไม่ใช่ความสะอาด** (P1):
 * · ถอดรูปคุกกี้ → ไลบรารีเปลี่ยนรูป → ถอดไม่ออก → **เงียบ** จนกว่าจะมีเคสที่เราจำได้ว่าต้องเขียน
 * · ประทับเอง   → API สาธารณะเปลี่ยน → **พังดัง**
 * **ของที่เราป้องกันคือข้อมูลส่วนตัว — ความเงียบจึงแพงเป็นพิเศษ**
 *
 * ## ✅ ทำไมตราถูกต้อง *โดยโครงสร้าง* ในเคสเป้าหมาย (P7)
 * > **ล็อกอินเป็นคนอื่นตอนไม่มีเน็ตไม่ได้ตามนิยาม** (login ต้องยิงเซิร์ฟเวอร์)
 * → *"เปิดแอปตอนออฟไลน์"* = เจ้าของไม่เปลี่ยนตั้งแต่ auth event ล่าสุด = **ตราตรงเสมอ**
 *
 * ## 🔴 รูที่เหลือ — เขียนไว้ ไม่กลบ
 * **สลับบัญชี: ผิดได้ 1 paint** (B ล็อกอินเสร็จ → provider เพิ่ง mount → ประทับ+ล้าง · ระหว่างนั้นเห็นของ A ได้)
 * · ⚠️ **แต่จังหวะนั้นออนไลน์เสมอ** (เพิ่งล็อกอิน) · โหลดถัดไปถูก
 * · 📌 ปิดเพิ่มได้ที่ `/auth/callback` (ล้างก่อน render) — **ยังไม่ตัดสินว่าคุ้ม**
 *
 * ## ⚠️ ห้ามใช้ไฟล์นี้ตัดสิน *สิทธิ์*
 * มันตอบว่า **"แคชก้อนนี้เป็นของใคร"** ไม่ใช่ **"คนนี้มีสิทธิ์ทำอะไร"** — สิทธิ์ตัดสินที่ RLS เท่านั้น
 * 🎯 ความต่างนี้คือเหตุผลที่ใช้ `onAuthStateChange` ได้ ทั้งที่กติกาห้ามเชื่อ session ฝั่ง client:
 * **กติกานั้นมีไว้สำหรับการตัดสินสิทธิ์ · ที่นี่เป็นคนละคำถาม** (P7 ชี้ · P1 รับ)
 */

/** 🔴 อยู่ **นอก** `trip-cache:` โดยตั้งใจ — ตราต้องรอด `clearAllCaches()` ไม่งั้นล้างแคชแล้วลืมว่าใครเป็นเจ้าของ */
const OWNER_KEY = "trip-device-owner";

/**
 * ใครเป็นเจ้าของข้อมูลในเครื่องนี้ · `null` = **ไม่รู้** (ไม่ใช่ "ไม่มีใคร")
 * 🔴 ผู้เรียกต้อง **fail closed** — ไม่รู้เจ้าของ = ไม่เสิร์ฟ · ห้ามตกเป็น "เสิร์ฟให้ทุกคน"
 */
export function readDeviceOwner(): string | null {
  if (typeof window === "undefined") return null;
  try {
    return window.localStorage.getItem(OWNER_KEY);
  } catch {
    // localStorage ถูกปิด — ตอบว่าไม่รู้ ซึ่งทำให้ผู้เรียก fail closed ตามที่ควร
    return null;
  }
}

/**
 * ประทับเจ้าของ · เรียกจาก `onAuthStateChange` เท่านั้น · `null` = ออกจากระบบแล้ว → ลบตรา
 *
 * 🔴 **และมันล้างข้อมูลเครื่องเองเมื่อเจ้าของเปลี่ยน — นั่นคือหัวใจของ `E6-AC14`** (2 ก.ย. 2026)
 *
 * ## ทำไมด่านต้องอยู่ที่นี่ ไม่ใช่ที่หน้าจอ
 * ก่อนหน้านี้ด่าน *"เจ้าของเปลี่ยนโดยไม่กด sign-out"* มีจุดเดียวคือ `HomeScreen.tsx:230`
 * · **ผู้อ่าน `lastTripId` อยู่ที่ `hooks/useActiveTripId.ts` ซึ่งถูกเรียกจาก `app/layout.tsx` (root)**
 * → ผู้ใช้ที่สลับบัญชีแล้วเปิด **ลิงก์ทริปตรง ๆ ตอนออฟไลน์** ไม่เคยผ่านหน้าแรกเลยสักครั้ง
 *   **ได้ `lastTripId` ของเจ้าของเก่าไปใช้ต่อ** (P4 เจอ · `de4b005` ปิดแค่เส้น sign-out ไม่ใช่คลาสทั้งหมด)
 *
 * 🎯 **แก้ด้วยการเอาคำถามออกจากผู้อ่าน:** ไม่ใช่ *"ผู้อ่านทุกจุดต้องตรวจเจ้าของ"* (ซึ่งเป็นรายการที่
 * ออกลูกไม่จบ — วันนี้ `useActiveTripId` ถูกเรียก 14 จุด) แต่เป็น ***"ตอนเจ้าของเปลี่ยน ข้อมูลของคนเก่าหายไปเลย"***
 * → ผู้อ่านไม่ต้องรู้เรื่องเจ้าของอีกต่อไป · **ไม่มีอะไรให้ลืมตรวจ**
 *
 * ## ⚠️ ล้างเฉพาะ "คนหนึ่ง → อีกคนหนึ่ง" — ไม่ใช่ทุกการเปลี่ยน
 * ```
 * null → X   ไม่ล้าง  ← เครื่องเปล่า/เพิ่งรู้จักเจ้าของ · ไม่มีข้อมูลของใครให้ล้าง
 * X → null   ไม่ล้าง  ← sign-out · `signOut()` ล้างเองอยู่แล้ว **ก่อน** ยิงเน็ต (`signIn.ts`)
 *                        🔴 ถ้าล้างที่นี่ด้วย session ที่กะพริบชั่วขณะจะกวาดแคชทิ้งโดยไม่มีใครสลับบัญชี
 * X → Y      **ล้าง**  ← สลับบัญชีบนเครื่องเดิม · เป็นเคสเดียวที่ `HomeScreen` เคยถือไว้คนเดียว
 * ```
 *
 * ## 🔴 ทำไม `void` ตรงนี้ปลอดภัย — และมันพึ่งสัญญาของไฟล์อื่น
 * `clearDeviceData()` ล้าง `localStorage` **ก่อน `await` ตัวแรก จึงรันแบบ synchronous**
 * (`lib/auth/deviceData.ts` เขียนสัญญานี้ไว้เอง และมีเคสที่เรียกโดยจงใจไม่ `await` ยืนยัน)
 * → `lastTripId` ซึ่งอยู่ใน `localStorage` **หายไปในจังหวะเดียวกับที่ตราถูกเปลี่ยน** ไม่มีหน้าต่างให้อ่านของเก่า
 * ⚠️ **ถ้าใครสลับลำดับใน `clearDeviceData()` บรรทัดนี้จะเปิดหน้าต่างขึ้นมาเงียบ ๆ** — เคสในไฟล์นั้นกันไว้แล้ว
 */
export function stampDeviceOwner(ownerId: string | null): void {
  if (typeof window === "undefined") return;

  const previous = readDeviceOwner();
  if (previous !== null && ownerId !== null && previous !== ownerId) {
    void clearDeviceData();
  }

  try {
    if (ownerId === null) window.localStorage.removeItem(OWNER_KEY);
    else window.localStorage.setItem(OWNER_KEY, ownerId);
  } catch {
    // เขียนไม่ได้ = อ่านกลับก็จะได้ `null` = fail closed · ไม่ใช่ error ที่ผู้ใช้ต้องเห็น
  }
}
