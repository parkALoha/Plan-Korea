/** ความยาวสูงสุดที่ยอมรับ — path จริงของเว็บนี้ไม่เคยยาวขนาดนี้ */
const MAX_LENGTH = 512;

export function safeNextPath(raw: string | null | undefined): string {
  if (!raw) return "/";
  if (raw.length > MAX_LENGTH) return "/";

  // ⚠️ `\` ไม่ใช่ตัวคั่น path ตามสเปก **แต่เบราว์เซอร์หลายตัวปรับให้เป็น `/` ก่อนเดินทาง**
  //    → `/\evil.example` กลายเป็น `//evil.example` = ออกนอกโดเมน
  //    การเช็คแค่ `startsWith("//")` จึงไม่พอ — นี่คือช่องที่ตัวตรวจฉบับแรกเปิดไว้
  //    เว็บนี้ไม่มี path ไหนต้องใช้ `\` เลย → ปฏิเสธทั้งหมด ง่ายกว่าและปลอดภัยกว่า
  if (raw.includes("\\")) return "/";

  // อักขระควบคุม — ใช้แยก header ได้ในบางบริบท และไม่มีทางเป็น path ที่ตั้งใจ
  if (/[\x00-\x1F\x7F]/.test(raw)) return "/";

  // ต้องเป็น path ภายในเท่านั้น
  if (!raw.startsWith("/")) return "/";
  // `//host` = protocol-relative URL → ออกนอกโดเมนทั้งที่ขึ้นต้นด้วย `/`
  if (raw.startsWith("//")) return "/";

  return raw;
}
