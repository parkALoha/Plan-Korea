/** ครั้งแรกของแต่ละจุดเท่านั้น — log ทุกคำขอจะกลบตัวเองจนไม่มีใครอ่าน */
const shouted = new Set<string>();

export function noteCacheFailure(
  where: string,
  error: { code?: string; message?: string } | null | undefined
): void {
  if (!error) return;
  if (shouted.has(where)) return;
  shouted.add(where);

  const isDenied = error.code === "42501";
  console.error(
    `🔴 แคช "${where}" ใช้งานไม่ได้ — ${isDenied ? "ไม่มีสิทธิ์ (42501)" : error.code ?? "ไม่ทราบรหัส"}: ${error.message ?? ""}\n` +
      (isDenied
        ? "   นี่คือ `Q3` ที่ยังไม่มีคำตอบ: **ไม่มีใครมีสิทธิ์เขียนแคชตอนใช้งานจริง**\n" +
          "   ผลที่ตามมา: ทุกคำขอเรียก provider ใหม่ทุกครั้ง · ค่าใช้จ่ายและเวลาตอบเต็มราคา\n" +
          "   🔴 อย่าแก้ด้วยการเปิดสิทธิ์ให้ไคลเอนต์ — นั่นคือการเปิดทางวางข้อมูลปลอมลงแคชที่คนอื่นใช้"
        : "   ตรวจว่าเป็นปัญหาชั่วคราวหรือเป็นสภาพถาวร ก่อนสรุปว่าไม่เป็นไร")
  );
}

/** สำหรับเทสต์ — ให้เคสถัดไปเห็นเสียงเหมือนครั้งแรก */
export function resetCacheFailureNotices(): void {
  shouted.clear();
}
