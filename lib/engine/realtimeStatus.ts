/**
 * 🔴 **ข้อความนี้เคยยืนยันข้อเท็จจริงของ *ฐาน* จากโค้ดที่ตรวจฐานไม่ได้** (P4 ชี้ · P1 แก้ · 2 ก.ย. 2026)
 *
 * ฉบับเดิมพิมพ์ว่า `no-op today, publication empty (E3-AC3)` — **เป็นคำอ้างเกี่ยวกับ publication
 * ซึ่งอยู่ในฐาน · ไฟล์นี้ไม่มีทางรู้ได้เลยว่ามันยังจริงอยู่ไหม**
 * · วันที่มีคนเปิด publication (โดยเฉพาะจาก Dashboard ซึ่งไม่ผ่านไฟล์ใด ๆ) hooks จะเริ่มได้ event จริง
 *   **แต่บรรทัดนี้ยังพิมพ์ข้อความเดิมทุกครั้ง — และมันแนบเลข `AC` มาด้วย จึงอ่านเหมือนผลของด่าน**
 * 🎯 **ข้อความที่เคยจริง กลายเป็นตัวหลอกที่ดูน่าเชื่อกว่าความจำคน เพราะมันมาจากโค้ด**
 *
 * ✅ **ฉบับนี้พูดเฉพาะสิ่งที่บรรทัดนี้รู้จริง** — ว่ามี subscribe เกิดขึ้น — แล้วชี้ไปที่ *ตัวที่ตอบได้*
 *    แทนที่จะตอบเอง · **คำอ้างที่ตรวจไม่ได้ ถูกถอดออก ไม่ได้ถูกทำให้แม่นขึ้น**
 * 📌 **ทางที่ยังไม่ได้ทำ และมันดีกว่านี้:** ให้ hooks เรียก `noteRealtimeEvent()` ตอนได้ event จริง
 *    → โค้ดจะ *สังเกต* แทนที่จะ *อ้าง* และจะดังเองวันที่โลกเปลี่ยน **ปิดช่อง Dashboard ที่ด่านฝั่งดิสก์ปิดไม่ได้**
 *    ราคา: ต้องแก้ 9 hooks คนละหนึ่งบรรทัด — ยังไม่ทำเพราะไฟล์เหล่านั้นมีเจ้าของอื่นกำลังทำงานอยู่
 */
export function noteRealtimeSubscribed(table: string): void {
  if (process.env.NODE_ENV === "production") return;
  console.debug(
    `[realtime] subscribed to "${table}". ` +
      "ยังไม่เคยยืนยันว่าเส้นนี้ส่ง event จริงหรือไม่ — อย่าสรุปจากการที่ subscribe สำเร็จ. " +
      "ตรวจของจริงได้ 2 ทาง: pg_publication_tables (โพรบ exposure) หรือดูว่ามี event เข้ามาจริงไหม. " +
      "บริบท: lib/engine/realtimeStatus.ts · E3-AC3"
  );
}
