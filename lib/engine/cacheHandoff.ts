/**
 * อ่านค่าที่ *เคย* อยู่ `localStorage` — IndexedDB ก่อน แล้วค่อยฝาแฝด
 * 🔴 คีย์เป็นสตริงเดียวกันทั้งสองที่โดยตั้งใจ (`tripKey` ของ `offlineStore` เขียนเหตุผลไว้เอง)
 */
export async function readHandoff<T>(key: string): Promise<T | null> {
  const fromStore = await storeGet<T>(key);
  if (fromStore !== null) return fromStore;
  // ⚠️ `null` จาก `storeGet` แปลว่า *ไม่มี* **หรือ** *อ่านไม่ได้* — แยกไม่ออกโดยสัญญาของมัน
  //    ทั้งสองกรณีเราอยากได้ฝาแฝด จึงไม่ต้องแยก (ถ้าวันหนึ่งต้องแยก ที่นี่คือจุดที่จะรู้ก่อน)
  return readCache<T>(key);
}

/**
 * เขียนค่าลง IndexedDB **แล้วเก็บฝาแฝดทิ้งเมื่อสำเร็จ** · คืน `false` เมื่อเขียนไม่ลง
 * 🔴 **ไม่ `await` ที่ผู้เรียก** — ดิสก์ต้องไม่หน่วงจอ · แต่ **ต้องดูค่าที่คืน** ไม่งั้นได้พฤติกรรม
 * เดียวกับ `writeCache` เดิมที่กลืนเงียบ ซึ่งเป็นสิ่งที่ `E6-AC7` ครึ่งแรกเพิ่งปิดไป
 */
export async function writeHandoff(key: string, value: unknown): Promise<boolean> {
  const ok = await storeSet(key, value);
  // 🔴 ลบ **หลัง** เท่านั้น — ลบก่อนแล้วเขียนไม่ลง = ข้อมูลหายทั้งสองที่ในจังหวะเดียว
  if (ok) clearCache(key);
  return ok;
}

/** เขียนแบบยิงแล้วลืม พร้อมเสียงเมื่อล้ม — ท่าที่ผู้เรียกทุกตัวใช้จริง รวมไว้ที่เดียวไม่ให้ใครลืมครึ่งหลัง */
export function writeHandoffNoisily(key: string, value: unknown, where: string): void {
  void writeHandoff(key, value).then((ok) => {
    if (!ok) noteCacheFailure(`offlineStore/${where}/write`, { code: "idb" });
  });
}
