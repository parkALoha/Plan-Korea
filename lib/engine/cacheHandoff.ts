import { readCache, clearCache } from "@/lib/localCache";
import { get as storeGet, set as storeSet } from "@/lib/engine/offlineStore";
import { noteCacheFailure } from "@/lib/engine/cacheGuard";

/**
 * `cacheHandoff` — สะพานชั่วคราวระหว่าง `localStorage` (ของเดิม) กับ IndexedDB (ของใหม่) · `E6-AC7` (`D17`)
 * เจ้าของ: P7-Mobile · 4 ก.ย. 2026 · **ไฟล์นี้มีวันตาย** — ดูหัวข้อสุดท้าย
 *
 * ## 🔴 ครึ่งที่ AC ไม่ได้เขียนไว้ และเป็นครึ่งที่ทำให้ AC เป็นจริงหรือไม่จริง
 * `E6-AC7` พูดถึงการ *ย้ายไปเขียนที่ใหม่* · **แต่ถ้าย้ายแล้วไม่เก็บของเก่า เราไม่ได้ลดอะไรเลย —
 * เราเพิ่มที่เก็บใบที่สองโดยที่ใบแรกยังเต็มเท่าเดิม** ⇒ *แย่กว่าก่อนย้าย* สำหรับเป้าหมายที่ AC ตั้งไว้
 * 🎯 รีโปนี้เรียนข้อนี้มาแล้วครั้งหนึ่ง — `hooks/personalLocalValue.ts` เขียนไว้เองว่า
 * ***"การลบคีย์เก่าคือครึ่งหนึ่งของงาน ไม่ใช่ของแถม"*** · ที่นั่นเป็นคีย์ดิบ → prefix · ที่นี่เป็น
 * `localStorage` → IndexedDB · **รูปเดียวกัน คนละชั้น**
 *
 * ## กติกาสองข้อ และเหตุผลที่มันไม่ใช่แค่ "อ่านสองที่"
 * ```
 * อ่าน   IndexedDB ก่อน → ไม่มีค่อยดูฝาแฝดใน localStorage   **ไม่เลื่อนขั้น ไม่ลบ**
 * เขียน  เขียน IndexedDB สำเร็จ → **ค่อยลบฝาแฝด**            ล้มเหลว = ไม่แตะของเก่า
 * ```
 * · 🔴 **ทำไมฝั่งอ่านต้องไม่เลื่อนขั้น (promote) ทั้งที่มันดูเป็นท่ามาตรฐาน:**
 *   การเลื่อนขั้นคือ *การเขียน* ที่เกิดขึ้นพร้อมกับการยิงของสด **และไม่มีใครคุมว่าใครจบก่อน**
 *   → ค่าเก่าที่เลื่อนขั้นช้ากว่า **ทับของสดที่เพิ่งลงไป** ⇒ ผู้ใช้เห็นของใหม่แล้วเปิดใหม่ได้ของเก่า
 *   🎯 **เป็นการแข่งกันแบบเดียวกับที่ `hydrateThenFetch` ถูกสร้างมาแก้ — แค่ย้ายจากชั้นจอไปชั้นดิสก์**
 *   ✅ ไม่เลื่อนขั้นแล้ว *ยังไม่เสียอะไร*: การยิงสำเร็จครั้งถัดไปเขียนของสดลง IndexedDB แล้วลบฝาแฝดให้เอง
 *   · ฝาแฝดจะรอดก็ต่อเมื่อ **ยังไม่เคยยิงสำเร็จเลยสักครั้ง** — ซึ่งเป็นกรณีที่เรา *ต้องการ* ให้มันรอด
 *
 * ## ⚠️ สิ่งที่ *ไม่* ได้แก้ และห้ามอ่านว่าแก้แล้ว
 * เครื่องที่ IndexedDB ใช้ไม่ได้ (โหมดส่วนตัวบางตัว · ที่เก็บถูกปิด) **จะไม่มีแคชออฟไลน์อีกต่อไป**
 * ฝาแฝดใน `localStorage` ยังอยู่ (เพราะเขียนไม่สำเร็จ = ไม่ลบ) **แต่ไม่มีใครอ่านมันหลังยิงสำเร็จครั้งแรก**
 * 🔴 **นี่คือการแคบลงจริงของพฤติกรรม ไม่ใช่ข้อจำกัดทางทฤษฎี** — จดไว้เพราะถ้าไม่จด
 * คนอ่านรอบหน้าจะนึกว่าฝั่งอ่านเป็น fallback ถาวร · **มันเป็นทางถอยตอน revert ไม่ใช่ทางเดินตอนรัน**
 *
 * ## 📌 ไฟล์นี้ตายเมื่อไหร่ — เขียนไว้เพราะสะพานที่ไม่มีวันตายคือหนี้ถาวร
 * เมื่อผู้เรียก `@/lib/localCache` เหลือเฉพาะ **ตราเจ้าของ** (`lib/auth/deviceOwner.ts`) ·
 * **ตัวล้าง** (`lib/auth/deviceData.ts`) · **แบนเนอร์เต็ม** (`hooks/useCacheFull.ts`) —
 * สามตัวนั้นอยู่ `localStorage` โดยตั้งใจ ไม่ใช่ของที่รอย้าย — **ลบไฟล์นี้ทั้งใบแล้วเรียก
 * `storeGet`/`storeSet` ตรง ๆ** · `lib/__tests__/localCacheRetirement.test.ts` นับผู้เรียกที่เหลือให้
 */

/**
 * อ่านค่าที่ *เคย* อยู่ `localStorage` — IndexedDB ก่อน แล้วค่อยฝาแฝด
 * 🔴 คีย์เป็นสตริงเดียวกันทั้งสองที่โดยตั้งใจ (`tripKey` ของ `offlineStore` เขียนเหตุผลไว้เอง)
 */
export async function readHandoff<T>(key: string): Promise<T | null> {
  const fromStore = await storeGet<T>(key);
  if (fromStore !== null) return fromStore;
  // ⚠️ `null` จาก `storeGet` แปลว่า *ไม่มี* **หรือ** *อ่านไม่ได้* — แยกไม่ออกโดยสัญญาของมัน
  //    ทั้งสองกรณีเราอยากได้ฝาแฝด จึงไม่ต้องแยก (ถ้าวันหนึ่งต้องแยก ที่นี่คือจุดที่จะรู้ก่อน)
  return readCache<T>(key);
}

/**
 * เขียนค่าลง IndexedDB **แล้วเก็บฝาแฝดทิ้งเมื่อสำเร็จ** · คืน `false` เมื่อเขียนไม่ลง
 * 🔴 **ไม่ `await` ที่ผู้เรียก** — ดิสก์ต้องไม่หน่วงจอ · แต่ **ต้องดูค่าที่คืน** ไม่งั้นได้พฤติกรรม
 * เดียวกับ `writeCache` เดิมที่กลืนเงียบ ซึ่งเป็นสิ่งที่ `E6-AC7` ครึ่งแรกเพิ่งปิดไป
 */
export async function writeHandoff(key: string, value: unknown): Promise<boolean> {
  const ok = await storeSet(key, value);
  // 🔴 ลบ **หลัง** เท่านั้น — ลบก่อนแล้วเขียนไม่ลง = ข้อมูลหายทั้งสองที่ในจังหวะเดียว
  if (ok) clearCache(key);
  return ok;
}

/** เขียนแบบยิงแล้วลืม พร้อมเสียงเมื่อล้ม — ท่าที่ผู้เรียกทุกตัวใช้จริง รวมไว้ที่เดียวไม่ให้ใครลืมครึ่งหลัง */
export function writeHandoffNoisily(key: string, value: unknown, where: string): void {
  void writeHandoff(key, value).then((ok) => {
    if (!ok) noteCacheFailure(`offlineStore/${where}/write`, { code: "idb" });
  });
}
