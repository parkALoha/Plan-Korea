/** รูปขั้นต่ำที่ต้องใช้ — รับได้ทั้ง `CatalogCity` ของฮุคและแถวจาก API โดยไม่ผูกกับใคร */
export type CityWithCenter = { slug: string | null; lat: number; lng: number };

/**
 * หาพิกัดกลางเมืองจากรายการเมืองที่โหลดมาแล้ว · **sync** — เรียกตอน render ได้เหมือนของเดิม
 *
 * 🎯 **ตัวนี้ไม่ยิงเน็ต และไม่ควรยิง** — ผู้เรียกทั้ง 5 รายเรียกมันตอน render
 * การทำให้เป็น `async` จะพาลำดับที่เคยได้ฟรีหายไปด้วย (`TEAM.md §3.4` — บทเรียนของ P7)
 * → **ข้อมูลต้องมาถึงผู้เรียกก่อนแล้ว** (`useTripCatalogCities` โหลดให้อยู่แล้ว)
 */
export function cityCenterOf(
  cities: readonly CityWithCenter[],
  citySlug: string | null | undefined,
): { lat: number; lng: number } | null {
  if (!citySlug) return null;
  const hit = cities.find((c) => c.slug === citySlug);
  if (!hit) return null;
  // 🔴 ป้องกันค่าที่ *ผ่านชนิดแต่ไม่ใช่พิกัด* — ฐานประกาศ `not null` แต่ข้อมูลเดินทางผ่าน JSON
  //    และ `NaN`/`Infinity` เป็น `number` ทั้งคู่ · **นี่คือบั๊กใบเดิมที่เรากำลังแก้ ไม่ใช่ของเผื่อ**
  if (!Number.isFinite(hit.lat) || !Number.isFinite(hit.lng)) return null;
  return { lat: hit.lat, lng: hit.lng };
}
