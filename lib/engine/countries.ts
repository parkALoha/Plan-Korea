/**
 * 🔴 **ใช้ `TravelMode` ของโดเมน ไม่ประกาศซ้ำ** — แก้ 27 ส.ค. 2026 (P2 เจอตอนต่อสาย)
 *
 * ฉบับแรกผมประกาศเป็นตัวพิมพ์ใหญ่ (`"WALK"|"TRANSIT"|"DRIVE"`) เพราะ **ตรงกับที่ Google Routes ใช้**
 * → `tsc` ปฏิเสธตอน P2 ส่ง `mode` เข้ามาตรง ๆ ทั้งที่ความหมายเดียวกัน · เขาต้องเขียนตัวแปลงในไฟล์ตัวเอง
 *
 * 🎯 **แต่ตัวพิมพ์เล็กคือของจริง และฐานเป็นคนบอก:**
 * ```sql
 * travel_mode text not null check (travel_mode in ('walk', 'transit', 'drive'))
 * ```
 * `lib/schedule.ts` ก็ประกาศตัวพิมพ์เล็กมาตั้งแต่ต้น · **ตัวพิมพ์ใหญ่เป็นภาษาของ *ตัวแปลง* ไม่ใช่ของ *โดเมน***
 * → ทะเบียนนี้อธิบาย**โดเมนของเรา** (ประเทศไหนมีโหมดจริงบ้าง) จึงต้องพูดภาษาโดเมน
 * · ⚠️ **ถ้าปล่อยไว้ ตัวแปลงที่ P2 เขียนจะถูกก๊อปไปที่จุดเรียกถัดไป** แล้วเราจะมีคำศัพท์สองชุด
 *   ที่ต้องคอยให้ตรงกันตลอดไป — รูปเดียวกับที่ทีมนี้ไล่ปิดกันทั้งวัน
 * · 📌 **`import type` เท่านั้น** — ถูกลบตอน compile จึงไม่ทำลายคุณสมบัติ "ไฟล์นี้ไม่ลากอะไรมาด้วย"
 */
import type { TravelMode } from "@/lib/schedule";

export type { TravelMode };

/** ผู้ให้บริการแผนที่ที่มีตัวสร้างลิงก์อยู่แล้วใน `lib/mapLinks.ts` */
export type MapProvider = "google" | "naver" | "kakao";

export type CountryCapabilities = {
  /**
   * โหมดที่ provider **ตอบเวลาจริงได้** · โหมดที่ไม่อยู่ในนี้ = ต้องติดป้าย "(ประมาณการ)"
   * 🔴 ใส่ชื่อลงที่นี่ได้ก็ต่อเมื่อ **มีคนยิงจริงแล้วเห็นว่ามันตอบ** ไม่ใช่เพราะเอกสารบอกว่ารองรับ
   */
  realTravelModes: readonly TravelMode[];
  /** เรียงตามลำดับที่อยากให้ผู้ใช้เห็น · ตัวแรกคือตัวหลัก */
  mapProviders: readonly MapProvider[];
};

/**
 * 🔴 **ค่าที่ประเทศซึ่งยังไม่มีแถวจะได้** — ปลอดภัยและใช้งานได้ ไม่ใช่ error
 * ดูเหตุผลเรื่องทิศของการเดาผิดในหัวไฟล์
 */
const UNKNOWN_COUNTRY: CountryCapabilities = {
  realTravelModes: [],
  mapProviders: ["google"],
};

/**
 * 🔴 **ค้นทะเบียนอย่างปลอดภัย — ห้าม index ตรง ๆ** (พบด้วยเทสต์ 27 ส.ค. 2026)
 *
 * ฉบับแรกเขียน `CAPABILITIES[countryCode.toLowerCase()] ?? UNKNOWN_COUNTRY`
 * → `countryCode = "constructor"` **คืนฟังก์ชัน `Object` ออกมาเป็นความสามารถของประเทศ**
 *   (`"__proto__"` คืน `Object.prototype`) · ทั้งคู่ truthy → `??` ไม่ช่วยเลย
 * → แล้ว `mapActionsFor()` เรียก `.map()` บน `undefined` → **`TypeError` พัง UI ทั้งหน้า**
 *
 * ⚠️ **วันนี้ยังไม่มีใครยิงค่านี้เข้ามาได้** (`catalog_cities` ไม่มี policy ฝั่งเขียนเลย)
 * — **แต่นั่นคือเหตุผลที่ต้องปิดตอนนี้ ไม่ใช่เหตุผลที่จะปล่อย** · `E7` จะ seed ตารางนั้น
 *   และแพลตฟอร์มจะให้ผู้ใช้สร้างเมืองในที่สุด · ตอนนั้นจะไม่มีใครกลับมาอ่านบรรทัดนี้
 * 🎯 **ฟังก์ชันที่โยน `TypeError` ใส่สตริงธรรมดา เป็นบั๊กอยู่แล้ว ไม่ต้องรอให้มีคนใช้ประโยชน์**
 */
function lookup(countryCode: string): CountryCapabilities | null {
  const key = countryCode.toLowerCase();
  return Object.hasOwn(CAPABILITIES, key) ? CAPABILITIES[key] : null;
}

/**
 * ⚠️ **นี่คือ *ข้อมูล* ไม่ใช่ *ตรรกะ*** — เพิ่มประเทศ = เพิ่มแถว · ห้ามมี `if` ไหนอ่านโค้ดประเทศตรง ๆ
 * 🔴 **เกาหลี `realTravelModes: ["TRANSIT"]` ไม่ใช่การเดา** — `PLAN.md §2` บันทึกไว้ว่า
 * ทดสอบจริงแล้ว Google ไม่คืนเส้นทาง `DRIVE`/`WALK` ในเกาหลีใต้ (ข้อจำกัดทางกฎหมาย)
 * และ `app/api/travel-time/route.ts:58` มีคอมเมนต์ที่บันทึกอาการเดียวกันไว้ตั้งแต่ก่อนมีไฟล์นี้
 */
const CAPABILITIES: Readonly<Record<string, CountryCapabilities>> = {
  kr: { realTravelModes: ["transit"], mapProviders: ["naver", "kakao", "google"] },
  vn: { realTravelModes: ["transit", "drive", "walk"], mapProviders: ["google"] },
};

/**
 * ความสามารถของประเทศหนึ่ง — **ไม่เคยโยน และไม่เคยคืน `null`**
 *
 * 🎯 ประเทศที่ไม่มีแถวได้ `UNKNOWN_COUNTRY` → **เพิ่มทริปญี่ปุ่นได้โดยไม่แตะโค้ดสักบรรทัด** (`E4-AC1`)
 * แล้วค่อยเพิ่มแถวเมื่อมีคนยืนยันความสามารถจริง — **การเพิ่มแถวคือการอัปเกรด ไม่ใช่การซ่อมของพัง**
 */
export function capabilitiesOf(countryCode: string | null | undefined): CountryCapabilities {
  if (!countryCode) return UNKNOWN_COUNTRY;
  return lookup(countryCode) ?? UNKNOWN_COUNTRY;
}

/**
 * เวลาเดินทางโหมดนี้ในประเทศนี้ **เป็นค่าจริง** หรือ **ประมาณการ**
 * `false` = UI ต้องติดป้าย "(ประมาณการ)" · **ตัดสินจาก registry ไม่ใช่จาก `if (country === "kr")`** (`E4-AC3`)
 */
export function hasRealTravelTime(countryCode: string | null | undefined, mode: TravelMode): boolean {
  return capabilitiesOf(countryCode).realTravelModes.includes(mode);
}

/**
 * ผู้ให้บริการแผนที่ที่ควรแสดงสำหรับประเทศนี้ เรียงตามลำดับ
 * 🔴 มีไว้แทนการ **ไม่ถามเลย** ซึ่งเป็นสภาพวันนี้ (`app/today/page.tsx` โชว์ Kakao เสมอ)
 *
 * ## 🔴 **ฐานเป็นเจ้าของ · ตารางในโค้ดเป็นค่าสำรอง** (แก้ 27 ส.ค. 2026 — P1 พบว่าตัวเองสร้างของซ้ำ)
 * `catalog_countries.nav_providers text[]` **มีอยู่ในฐานตั้งแต่ `20260825132854` แล้ว**
 * และคอมเมนต์ของ migration นั้นเขียนไว้ตรง ๆ ว่ามันคือปลายทางของคำถาม
 * *"วันนี้อยู่ประเทศไหน ใช้ Naver ได้ไหม"* พร้อมเหตุผลว่าทำไมเป็นรายชื่อ ไม่ใช่ `has_naver`
 * → **ผมสร้าง `CAPABILITIES` ในโค้ดขึ้นมาตอบคำถามเดียวกัน โดยไม่รู้ว่าฐานตอบได้อยู่แล้ว**
 * · `rlsMatrix.test.ts:1950` ทดสอบคอลัมน์นั้นอยู่ **แต่ไม่มีโค้ดแอปไหนอ่านมันเลยสักบรรทัด**
 *
 * 🎯 **และนี่คือสิ่งที่ทำให้ `E4-AC1` ผ่านไม่ได้:** เกณฑ์บอกว่าเพิ่มประเทศ = แก้ข้อมูล 1 ที่
 * แล้ว `git diff --stat` ของโฟลเดอร์โค้ดต้องได้ **0 ไฟล์** — **ถ้าทะเบียนอยู่ในโค้ด มันได้ 1 เสมอ**
 *
 * ⚠️ **แต่ไม่ได้ย้ายทั้งหมดไปฐาน** — `realTravelModes` ยังอยู่ในโค้ดโดยตั้งใจ
 * เพราะมันไม่ใช่คุณสมบัติของ*ประเทศ* แต่เป็นคุณสมบัติของ**การต่อ Google ของเรา**
 * (เกาหลี*มี*เส้นทางขับรถ · Google แค่ไม่ให้เรา) → เปลี่ยนเมื่อเราเปลี่ยนผู้ให้บริการ ไม่ใช่เมื่อโลกเปลี่ยน
 *
 * 🔴 **`nav_providers` มี `default '{}'`** → ประเทศที่ยังไม่ตั้งค่าจะได้ลิสต์ว่าง
 * **ลิสต์ว่างต้องแปลว่า "ยังไม่ตั้งค่า" ไม่ใช่ "ไม่มีแผนที่"** — ไม่งั้นประเทศใหม่จะไม่มีปุ่มนำทางเลย
 */
export function mapProvidersFor(
  countryCode: string | null | undefined,
  navProvidersFromDb?: readonly string[] | null,
): readonly MapProvider[] {
  const fromDb = (navProvidersFromDb ?? []).filter(isMapProvider);
  return fromDb.length > 0 ? fromDb : capabilitiesOf(countryCode).mapProviders;
}

/**
 * 🔴 **กรองค่าที่ฐานส่งมา — `nav_providers` เป็น `text[]` เปล่า ๆ ไม่มี CHECK บังคับ**
 * แถวที่มี `"bing"` อยู่ข้างในจะทำให้ `actionFor()` เจอ provider ที่ไม่มีตัวสร้างลิงก์
 * · ทิ้งตัวที่ไม่รู้จัก **แล้วถ้าทิ้งจนหมด ให้ตกไปใช้ค่าสำรอง** ไม่ใช่คืนลิสต์ว่าง
 */
function isMapProvider(v: string): v is MapProvider {
  return v === "google" || v === "naver" || v === "kakao";
}

/** ประเทศที่มีแถวจริงในทะเบียน — สำหรับเทสต์และเครื่องมือ **ไม่ใช่สำหรับตรรกะของแอป** */
export function countriesWithCapabilities(): readonly string[] {
  return Object.keys(CAPABILITIES);
}

/**
 * ควร **ข้ามการยิง API** สำหรับโหมดนี้ในประเทศนี้ไหม — `E4-AC5` (ประหยัด quota · ไม่ให้ผู้ใช้รอเปล่า)
 *
 * ## 🔴 ทำไมไม่ใช้ `!hasRealTravelTime()` ตรง ๆ — P2 จับได้ก่อนผมจะทำพัง
 * `hasRealTravelTime()` คืน `false` กับ **สองกรณีที่ต่างกันมาก**:
 * ```
 * kr / DRIVE   → false  เพราะ **รู้แน่ว่าไม่มี** (ทดสอบจริงแล้ว · PLAN.md §2)
 * jp / DRIVE   → false  เพราะ **ยังไม่รู้อะไรเลย** (ไม่มีแถวในทะเบียน)
 * ```
 * · ใช้กรองด้วยตัวเดียวกัน → **ประเทศที่ไม่รู้จักจะไม่ถูกยิงตลอดกาล**
 *   → **ไม่มีวันรู้ว่าญี่ปุ่นตอบ `DRIVE` ได้จริงไหม เพราะเราไม่เคยถาม**
 *   → ทะเบียนจะ "ถูก" ตลอดไป **โดยไม่มีใครท้าทายมันได้** — คำทำนายที่ทำให้ตัวเองเป็นจริง
 *
 * 🎯 **ข้ามได้เฉพาะเมื่อประเทศนั้น *อยู่ในทะเบียนแล้ว* และระบุไว้ว่าไม่มีโหมดนี้**
 * ประเทศที่ไม่รู้จัก = **ยิงตามปกติ แล้วให้ผลจริงสอนเรา** — นั่นคือทางเดียวที่ทะเบียนจะได้แถวใหม่ที่มีหลักฐาน
 *
 * ⚠️ **และนี่ไม่ใช่ตัวตัดสินว่า "จริงหรือประมาณ"** — ตัวนั้นคือผลที่ยิงกลับมาจริง (`isTravelTimeReal`)
 * ซึ่ง**แม่นกว่าทะเบียนเสมอ** เพราะเป็นความจริงที่สังเกตแล้ว ไม่ใช่ค่าที่คาดไว้
 * **ทะเบียนตอบว่า "อย่ายิง" ไม่ใช่ "อย่าเชื่อ"**
 */
export function shouldSkipTravelApi(
  countryCode: string | null | undefined,
  mode: TravelMode
): boolean {
  if (!countryCode) return false;
  const known = lookup(countryCode);
  if (!known) return false; // ไม่รู้จัก → ยิง แล้วให้ผลจริงสอนเรา
  return !known.realTravelModes.includes(mode);
}

/**
 * ควรข้ามการยิง API สำหรับ **ขาเดินทางหนึ่งขา** ไหม — `E4` · P1 ตัดสิน 27 ส.ค. 2026 (P5 ชี้ช่อง)
 *
 * ## 🔴 ช่องที่ P5 พบ: `shouldSkipTravelApi()` รับ **ประเทศเดียว** แต่ขาเดินทางเชื่อม **สองจุด**
 * ทริปนี้มีวันข้ามประเทศ 3 วัน ตั้งแต่วันแรก (โซล ↔ ฮานอย) →
 * **"ขานั้นควรใช้ความสามารถของประเทศไหน — ต้นทางหรือปลายทาง"** ไม่เคยมีใครตัดสิน
 *
 * ⚠️ **วันนี้ยังไม่กัด เพราะขาข้ามประเทศทุกขาเป็นแถว `kind='intercity'` ซึ่งถือเวลาจากตั๋วที่จองแล้ว**
 * — แต่นั่นคือ *"ถูกเพราะกฎอื่นบังเอิญคลุมอยู่"* ไม่ใช่ *"ถูกเพราะตัดสินไว้"* (P5 เรียกว่าญาติของ `D54` และถูก)
 *
 * ## 🎯 ตัดสิน: **ข้ามได้เฉพาะเมื่อทั้งสองปลายอยู่ประเทศเดียวกัน และประเทศนั้นรู้แน่ว่าไม่มีโหมดนี้**
 * ข้ามประเทศ → **ยิงเสมอ ไม่ข้าม**
 *
 * 🔴 **ที่ไม่เลือกทาง "ขาข้ามประเทศ = ประมาณการเสมอ" (ข้อเสนอแรกของ P5)** เพราะมันขัดกับ
 * ข้อที่คมกว่าของ P5 เองในข้อความเดียวกัน:
 * > *"เอาค่า**ทำนาย**ไปเป็น `source` ตรง ๆ = ติดป้าย (ประมาณการ) **ทับข้อมูลจริง**"*
 * ถ้าเราติดป้ายล่วงหน้า แล้ว Google ตอบข้อมูลจริงมา **เราจะโกหกผู้ใช้ในทิศที่กู้ยาก**
 * · ทะเบียนตอบว่า **"อย่ายิง"** ไม่ใช่ **"อย่าเชื่อ"** — ประโยคนี้อยู่ในไฟล์นี้มาก่อนแล้ว และมันคุมข้อนี้ด้วย
 *
 * 📌 **ป้าย "จริง/ประมาณการ" ต้องมาจาก *ผลที่ยิงกลับมา* เสมอ ไม่ใช่จากฟังก์ชันนี้**
 */
export function shouldSkipTravelApiForLeg(
  fromCountry: string | null | undefined,
  toCountry: string | null | undefined,
  mode: TravelMode,
): boolean {
  // ไม่รู้ปลายใดปลายหนึ่ง → ยิง (ให้ผลจริงสอนเรา · เหมือน `shouldSkipTravelApi`)
  if (!fromCountry || !toCountry) return false;
  // ข้ามประเทศ → ยิงเสมอ · เราไม่มีนิยามว่าความสามารถของขานี้เป็นของใคร **และการเดาที่นี่ราคาแพงกว่าการยิง**
  if (fromCountry.toLowerCase() !== toCountry.toLowerCase()) return false;
  return shouldSkipTravelApi(fromCountry, mode);
}
