import type { Place } from "@/data/places";

/**
 * รูปคำตอบของ `GET /api/engine/trips/<id>/stops` — **รับได้ทั้งของเก่าและของใหม่** · `E6-AC13`
 * เจ้าของ: P3-FE/Perf · 2 ก.ย. 2026
 *
 * ## 🔴 ทำไมต้องรับสองรูป ทั้งที่ไคลเอนต์กับเซิร์ฟเวอร์ deploy พร้อมกัน
 * `AC13` เปลี่ยนคำตอบจาก `StopDto[]` เป็น `{ stops, places }` — **อาเรย์ → อ็อบเจกต์ อ่านสลับกันไม่ได้เลย**
 * · หน้าที่เปิดค้างไว้ตอน deploy ยังเป็นโค้ดเก่า แล้วยิงไปเจอเซิร์ฟเวอร์ใหม่ → `rows.length` บนอ็อบเจกต์
 *   = `undefined` → **จุดแวะหายทั้งวันโดยไม่มี error** (ไม่ใช่หน้าพัง ซึ่งจะสังเกตง่ายกว่า)
 * · ⚠️ ช่วงเวลานั้นสั้น **แต่ไม่ใช่ศูนย์ และมันเงียบ** — ตัว parse ที่รับสองรูปมีราคาถูกกว่าการไปตามหาทีหลังมาก
 *
 * ## 📌 สิ่งที่ *ไม่* เปลี่ยน และตั้งใจไม่เปลี่ยน — **รูปแคชในเครื่อง**
 * `useStops` เก็บ `TripStop[]` (แถวที่แปลงแล้ว) ไว้ที่ `stops:<planId>` มาตั้งแต่ต้น
 * 🔴 **`places` จะไปอยู่คีย์แยก ไม่ยัดลงคีย์เดิม** — ถ้ายัดรวม ผู้ใช้ที่อัปเดตโค้ดตอนออนไลน์แล้วออฟไลน์ทันที
 * จะมีแคชรูปเก่าที่โค้ดใหม่อ่านไม่ออก = **ออฟไลน์พังเงียบสำหรับคนที่ยังไม่เคยโหลดใหม่หลังอัปเดต**
 * · 🎯 **แยกคีย์ = แคชเก่าอ่านได้โดยนิยาม ไม่ต้องมีโค้ดแปลงรุ่น** และ "ไม่มี `places`" ตกลงเป็น
 *   *ชื่อสถานที่จากคลังยังไม่มาตอนออฟไลน์* ซึ่งเป็นการเสื่อมที่ยอมรับได้ ไม่ใช่การพัง
 */
export type StopsPayload<T> = {
  stops: T[];
  /** `{}` = เซิร์ฟเวอร์รุ่นเก่า (ยังไม่ส่ง side-map) — **ไม่ใช่ "ไม่มีสถานที่"** */
  places: Record<string, Place>;
};

function isPlaceMap(v: unknown): v is Record<string, Place> {
  return typeof v === "object" && v !== null && !Array.isArray(v);
}

/**
 * `null` = อ่านไม่ออก (ผู้เรียกต้องแยก *"ถามไม่ได้"* ออกจาก *"ไม่มีจุดแวะ"* — คนละสถานะ)
 *
 * ⚠️ **ไม่ตรวจเนื้อในของแต่ละแถว** โดยตั้งใจ — นั่นเป็นงานของ `mapStopRows` ซึ่งมีเคสของตัวเองอยู่แล้ว
 * ที่นี่ตอบคำถามเดียว: *"ซองจดหมายรูปไหน และมีแถวอยู่ตรงไหน"*
 */
export function parseStopsPayload<T>(raw: unknown): StopsPayload<T> | null {
  if (raw === null || raw === undefined) return null;
  // รูปเก่า: อาเรย์เปล่า ๆ — `[]` ยังต้องแปลว่า "ทริปนี้ไม่มีจุดแวะ" ไม่ใช่ "อ่านไม่ออก"
  if (Array.isArray(raw)) return { stops: raw as T[], places: {} };
  if (typeof raw !== "object") return null;
  const o = raw as { stops?: unknown; places?: unknown };
  if (!Array.isArray(o.stops)) return null;
  return { stops: o.stops as T[], places: isPlaceMap(o.places) ? o.places : {} };
}

/**
 * เขียน side-map ลงแคชได้ไหม — **`{}` คือสัญญาณของการเสื่อม ไม่ใช่ข้อมูล**
 *
 * 🔴 route คืน `places: {}` เมื่อคิวรีคลังล้ม (จุดแวะยังมาครบ · `console.error` ฝั่งเซิร์ฟเวอร์)
 * ทับแคชด้วยมัน = **คลังล่มหนึ่งครั้ง แล้วผู้ใช้เสียชื่อสถานที่ตอนออฟไลน์ไปจนกว่าจะออนไลน์อีกครั้ง**
 * · รูปเดียวกับกฎ *ห้ามทับแคชด้วยผลที่หดเพราะสะพานวันไม่ครบ* — คนละสาเหตุ เหตุผลเดียวกัน
 * ⚠️ **อยู่ที่นี่ ไม่ใช่ใน `hooks/useStops.ts` — และไม่ใช่เรื่องการจัดระเบียบ**
 *    ไฟล์ hook ลาก `lib/supabase` เข้ามา → `createClient` ต้องการ WebSocket ที่ Node 20 ไม่มี
 *    → เทสต์ที่ import จากที่นั่น **ล้มตอนโหลด suite** และ vitest รายงานว่า *"no tests"*
 *    ซึ่งอ่านผ่านตาได้ง่ายมากว่าเป็นสีเขียว (ผมเจอกับตัวตอนเขียนเคสนี้เอง)
 *    · รูปเดียวกับที่ `classifyLegacyDayPlan` · `hydrateThenFetch` · `dayBridge` ถูกแยกออกมา
 */
export function shouldCacheSideMap(places: Record<string, Place>): boolean {
  return Object.keys(places).length > 0;
}
