/**
 * สถานะของหน้าที่เรนเดอร์วันจาก `data/itinerary.ts` ล้วน (`/today` · `/summary`) — `E4`/`E5`
 * เจ้าของ: P3-FE/Perf · 28 ส.ค. 2026
 *
 * 🔴 **ไฟล์นี้ไม่ import อะไรเลยโดยตั้งใจ** — เหตุผลเดียวกับที่ `lib/engine/dayBridge.ts` เขียนไว้เอง:
 * ตรรกะที่อยู่ในไฟล์ที่ลาก `lib/supabase` เข้ามา **ทดสอบไม่ได้บน Node 20** (`createClient` ต้องการ
 * native WebSocket ที่ยังไม่มี) → เคสจะล้มตอน import ก่อนถึงตัว assertion ด้วยซ้ำ
 * · เจอกับตัวจริงตอนเขียนเทสต์รอบแรก: ไฟล์เทสต์ import hook → **0 เคสถูกรัน** และ vitest รายงานว่า
 *   suite ล้ม ไม่ใช่เคสแดง — *"ไม่มีอะไรพัง" กับ "ไม่ได้ตรวจอะไร" ให้ผลเหมือนกันเป๊ะ*
 */

/**
 * `"loading"`    — ยังไม่รู้ (แสดง skeleton · ห้ามแสดงเนื้อหา)
 * `"unreadable"` — **ถามไม่ได้** (ออฟไลน์/เน็ตสะดุด/500) — สถานะของ *การเชื่อมต่อ*
 * `"unsupported"` — **หน้านี้ยังไม่รองรับทริปนี้** — และวันนี้ **ทุกทริปได้สถานะนี้** (ดูบล็อกล่าง)
 *
 * 🔴 **`"legacy"` ถูกถอดออกจาก type โดยตั้งใจ** (P1 ตัดสิน · 28 ส.ค. 2026) — ไม่ใช่แค่ "เลิกคืนค่านั้น"
 * แต่ทำให้ **สถานะที่ทำให้เรนเดอร์แผนเกาหลีได้ ไม่มีอยู่ในชนิดข้อมูลอีกต่อไป** · ใครจะเปิดทางกลับ
 * ต้องแก้ type ก่อน = เป็นการตัดสินใจที่มองเห็น ไม่ใช่การเผลอ
 */
export type LegacyDayPlanState = "loading" | "unreadable" | "unsupported";

/**
 * ตัดสินสถานะจากผลที่ได้ — **ฟังก์ชันบริสุทธิ์ เพื่อให้ทดสอบได้โดยไม่ต้อง render hook**
 * (รีโปนี้ไม่มี `@testing-library/react` — ถ้าตรรกะอยู่ในตัว hook ล้วน **จะไม่มีทางมีเคสที่พิสูจน์ว่า
 * `foreign` ถูกตรวจจริง** ซึ่งเป็นกิ่งเดียวที่บั๊ก "ทริปญี่ปุ่นแสดงแผนเกาหลี" ทั้งบั๊กขึ้นอยู่กับมัน)
 *
 * ## 🔴 ทำไมไม่ใช่ `matched === 0` — **วัดแล้วมันไม่จับเคสที่รายงานมา**
 * มติแรก (P1 อนุมัติ) คือใช้ `bridge.matched === 0` · ผมรันกับข้อมูลจริงของทริปที่ P1 ยิงแล้วพบว่า**มันไม่พอ**:
 * ```
 * ITINERARY       2026-10-11 → 2026-10-21   (11 วัน)
 * ทริปญี่ปุ่น        2026-10-11 → 2026-10-14   (4 วัน)
 * buildDayBridge  matched = 4  →  matched === 0 เป็นเท็จ  →  ตอบ "legacy"  →  **ยังแสดงแผนเกาหลีเหมือนเดิม**
 * ```
 * 🎯 **`buildDayBridge` จับคู่ด้วย *วันที่ปฏิทินล้วน ไม่ผูกกับ `tripId`*** (เขียนไว้เองที่หัว `dayBridge.ts`
 * · ผมรายงานเป็นความเสี่ยงเชิงโครงสร้างไว้ตั้งแต่ `§18` แต่ตอนนั้นสรุปว่า "ยิงไม่ได้จริง")
 * **ทริปคนละใบที่ช่วงวันทับกัน จึงจับคู่กันได้** — และทริปทดสอบของ P1 ทับพอดีเพราะสร้างช่วงเดียวกับทริปจริง
 *
 * ## 🔴 เกณฑ์ "ตรงทั้งชุด" ก็ยังไม่พอ — **ถอนแล้ว 28 ส.ค. 2026 (P1 ตัดสิน (ข))**
 * ของถัดมาคือ `legacy` เมื่อ `matched === rows.length && rows.length === legacyDayCount` · ผมเขียนกำกับไว้เอง
 * ว่ายังมีรูสำหรับ *"ทริปที่บังเอิญมี 11 วันตรง 11–21 ต.ค. 2026 เป๊ะ"* แล้ว **P1 ไปเปิดฐานเจอตัวอย่างจริง**:
 * ```
 * trip 9d26d2ba…  11 วัน  2026-10-11 … 2026-10-21   matched 11/11  →  "legacy"  →  แสดงแผนเกาหลี
 *   เจ้าของเป็นบัญชี @gmail.com **ไม่ใช่ fixture** — ผู้ใช้จริงเห็นเที่ยวบิน/ที่พักที่เขาไม่ได้ใส่
 * ```
 * 🎯 **ไม่มี heuristic จากรูปข้อมูลอันไหนแยก "สำเนาที่เหมือนต้นฉบับทุกช่อง" ออกจาก "ต้นฉบับ" ได้** —
 * ทริปใบนี้ผ่านทั้งเกณฑ์นี้ **และ** เกณฑ์ `cities.length === 0` ของ `TripPlanScreen` พร้อมกัน
 * → **เอาสองเกณฑ์มา AND กันก็ไม่ช่วย** · ที่ขาดคือ *สัญญาณตัวตน* ซึ่ง `grep` ยืนยันแล้วว่าไม่มีในฐาน
 * · 📌 และช่วงวันที่ทำให้เกิดคือ **ช่วงของทริปจริง** — คนที่วางแผนช่วงเดียวกัน หรือสร้างทริปเลียนแบบทริปจริง
 *   **คือกรณีที่น่าจะเกิดที่สุด ไม่ใช่เคสสุดโต่ง** · fixture แบบนี้จะมีเพิ่ม ไม่ใช่ลดลง
 *
 * ## ✅ สิ่งที่ทำแทน: **ปฏิเสธทุกทริป** จนกว่า `B6` จะต่อเข้า `/today` + `/summary`
 * 🔴 **ไม่ใช่การประนีประนอม — บนฐาน `platform` วันนี้ไม่มีทริปใบไหนที่การเรนเดอร์ `data/itinerary.ts`
 * เป็นคำตอบที่ถูกเลยสักใบ** (ทริปเกาหลีจริงอยู่ production บน `main` · `E7` ยังไม่ย้าย)
 * → ทุกครั้งที่ด่านเคยตอบ `legacy` **มันตอบผิดโดยโครงสร้าง ไม่ใช่ผิดเป็นบางกรณี** · เราไม่ได้เสียความสามารถ
 * อะไรเลย เพราะไม่เคยมีทริปที่มันใช้ได้ตั้งแต่แรก
 *
 * 🔴 **เงื่อนไขที่จะถอนการปฏิเสธนี้คือ `B6` เท่านั้น — ไม่ใช่ "เกณฑ์ที่ฉลาดขึ้น"**
 * ทุกเกณฑ์ที่อ่านจากรูปข้อมูลจะพลาดกับสำเนาที่เหมือนต้นฉบับเสมอ · ทางออกคือให้สองหน้านี้อ่านวันจากฐาน
 * ผ่าน `usePlatformItinerary` เหมือนที่ `TripPlanScreen` ทำ **หรือ** มีสัญญาณตัวตนจาก `E7`
 *
 * ⚠️ **ห้าม merge เข้า `main` ก่อน `B6`** — บน `main` ทริปเกาหลีจริง**ยังพึ่งสองหน้านี้อยู่** การปฏิเสธ
 * ทุกทริปที่นั่นจะทำให้ผู้ใช้จริงเปิด `/today`/`/summary` ไม่ได้เลย · วันนี้ `main` freeze อยู่แล้ว
 * **แต่กติกาไม่ควรพึ่ง freeze** (`TEAM.md` — freeze เป็นสถานะ ไม่ใช่ด่าน)
 *
 * @param rows แถวจาก `/days` · `null` = อ่านไม่ได้ (fetch ล้ม)
 */
export function classifyLegacyDayPlan(rows: readonly unknown[] | null): LegacyDayPlanState {
  // 🔴 อ่านไม่ได้ → `unreadable` · แยกจาก `unsupported` เพราะ **ผู้ใช้ทำคนละอย่าง**:
  //    อ่านไม่ได้ = ต่อเน็ตแล้วลองใหม่ได้เอง · ไม่รองรับ = รอระบบ ไม่มีอะไรให้เขาทำ
  if (!rows) return "unreadable";
  // 🔴 **ทุกทริปที่อ่านได้ → `unsupported`** — ไม่มีกิ่งไหนคืนค่าที่ทำให้เรนเดอร์ `ITINERARY` ได้อีก
  //    (และ `"legacy"` ไม่มีอยู่ใน type แล้ว จึงเขียนกลับมาโดยเผลอไม่ได้)
  return "unsupported";
}
