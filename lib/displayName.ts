/**
 * **เพดานความยาว "ชื่อที่แสดง" และวิธีนับ — แหล่งเดียวของทั้งเว็บ**
 * ผู้ใช้ตัดสินเอง 4 ก.ย. 2026: *"ชื่อคนทั่วไป คนไทย หรือตั้งเล่น ก็ไม่ควรเกิน 20 ตัวอักษร"*
 * และเลือกให้ **20 หมายถึงตัวที่ตาเห็น** เพื่อให้ *"ไม่มีใครเสียเปรียบ"*
 *
 * ## 🔴 ทำไมต้องอยู่ไฟล์เดียว ไม่ใช่ประกาศซ้ำสองที่
 * หน้าเว็บ (`app/account/DisplayNameField.tsx`) กับด่าน (`app/api/engine/profile/route.ts`)
 * ต้องได้คำตอบ **เท่ากันเสมอ** · ไฟล์ทั้งสองเคยจดกฎนี้ไว้เองว่า
 * ***"ตัวนับที่นับคนละแบบกับด่าน คือตัวนับที่โกหก"*** — ผู้ใช้จะเห็นว่า "ยังเหลือที่" แล้วโดน `400`
 * 🎯 **ค่าคงที่ที่ต้องเท่ากัน แต่ถูกพิมพ์ไว้สองที่ จะต่างกันวันใดวันหนึ่งเสมอ — และไม่มีอะไรส่งเสียงตอนมันต่าง**
 * ⇒ ตัดความเป็นไปได้นั้นทิ้ง แทนที่จะเขียนคอมเมนต์เตือนให้คนจำ
 *
 * ## 🔴 ทำไมไม่ใช่ `.length` และไม่ใช่ `Array.from` เช่นกัน
 * ```
 * "เปี๊ยก"   .length = 6  ·  Array.from = 6  ·  ตาเห็น = 4
 * "ก้อง"     .length = 4  ·  Array.from = 4  ·  ตาเห็น = 3
 * "ก้อง 🎒"  .length = 7  ·  Array.from = 6  ·  ตาเห็น = 5
 * ```
 * · `.length` นับ UTF-16 code unit ⇒ อีโมจิเป็น 2
 * · `Array.from` นับ code point ⇒ อีโมจิถูกแล้ว **แต่สระ/วรรณยุกต์ไทยยังเป็นตัวแยก**
 *   ⇒ ชื่อไทยกินโควตามากกว่าที่ตาเห็น ~30% · วัดจริง: `ประวิทย์ วงศ์สุวรรณชัย` = 22 code point แต่ตาเห็น 17
 *   🔴 **นั่นแปลว่าเพดานเดียวกันเข้มกับคนไทยกว่าคนใช้อักษรละติน โดยไม่มีใครตั้งใจ**
 * · `Intl.Segmenter` นับ **grapheme cluster** = สิ่งที่คนเรียกว่า "ตัวอักษร" จริง ๆ
 *
 * ⚠️ **ตัวแบ่งไม่ผูกกับภาษา** (`undefined` locale) — เพดานต้องไม่ขึ้นกับว่าใครกำลังใช้ภาษาอะไร
 */
export const DISPLAY_NAME_MAX = 20;

const graphemes = new Intl.Segmenter(undefined, { granularity: "grapheme" });

/** นับ "ตัวอักษรที่ตาเห็น" — ใช้ตัวนี้ทั้งฝั่งหน้าเว็บและฝั่งด่าน ห้ามนับเองที่อื่น */
export function countDisplayNameChars(value: string): number {
  return [...graphemes.segment(value)].length;
}
