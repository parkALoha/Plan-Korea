/**
 * ตัวตัดสินว่า "รอบนี้อ่านเป็นเขียวได้ไหม" — **ไม่มี side effect ไม่แตะ fs** จึงนำเข้าจาก
 * `vitest.config.mts` ได้ปลอดภัย (`_helpers.ts` อ่านโฟลเดอร์ migration ตอนโหลด จึงเอามาใช้ตรงนี้ไม่ได้)
 *
 * ## ทำไมต้องมี — วัดมาแล้ว ไม่ใช่สมมติ (P4 · 26 ส.ค. 2026)
 * รันชุดนี้โดยไม่มี creds และไม่ตั้ง `RLS_MATRIX_REQUIRED=1`:
 * ```
 * Test Files  1 passed (1)
 *      Tests  26 passed | 230 skipped (256)     ← 230 เคสไม่ได้รันเลย
 * exit code 0                                    ← และมันบอกว่า "ผ่าน"
 * ```
 * 🔴 **`describe.runIf(hasCreds)` ข้ามทั้งชุดเงียบ ๆ แล้ววิตเทสต์รายงานว่าไฟล์ "passed"**
 * `requireLiveCreds` แปลงมันเป็น fail ได้ **เฉพาะเมื่อมีคนจำได้ว่าต้องตั้งธง**
 * → **ความถูกต้องขึ้นกับความจำของคนสั่งรัน ซึ่งเป็นที่เดียวที่เราห้ามให้มันขึ้นอยู่กับ**
 *
 * 🎯 **และ P1 เจอทางที่สองในวันเดียวกัน:** `beforeAll` ล้ม → เคสในบล็อกนั้นขึ้นเป็น **skipped**
 * → บรรทัด `Tests  487 passed | 3 skipped` **อ่านเหมือนผ่าน** · `Failed Suites 1` อยู่คนละบรรทัด
 * และ `grep -E "AssertionError|Tests "` ที่เราใช้กันทั้งวัน **มองไม่เห็นบรรทัดนั้นเลย**
 * · ⚠️ ทางนี้ exit code ไม่ใช่ 0 อยู่แล้ว **แต่คนอ่านสรุปผิดได้ และเกิดขึ้นแล้วจริง**
 *
 * 📌 **ขอบเขต: ตัวนี้ตอบว่า *เคสได้รันไหม* ไม่ได้ตอบว่า *เคสถูกไหม***
 *    ตัวนับ `E2-AC11` อ่านจากซอร์สว่ามีเคสอยู่ · ตัวนี้อ่านจากผลว่าเคสเดินจริง — **คนละคำถาม ต้องมีทั้งคู่**
 */
export type RunSummary = {
  /** เคสที่ถูกข้าม ไม่ว่าจะด้วย `runIf` หรือเพราะ `beforeAll` ของบล็อกนั้นล้ม */
  skipped: number;
  /** suite ที่โหลด/รันไม่สำเร็จ — เคสข้างในไม่เคยถูกประเมินเลย */
  suiteErrors: number;
  /** เคสทั้งหมดที่เก็บได้ · ใช้กันกรณี "ไม่มีอะไรให้รัน" ซึ่งก็อ่านเป็นเขียวได้เหมือนกัน */
  total: number;
};

/** คืนข้อความเหตุผลถ้ารอบนี้อ่านเป็นเขียวไม่ได้ · คืน `null` ถ้าอ่านได้ */
export function runIntegrityFailure(s: RunSummary): string | null {
  const why: string[] = [];
  if (s.total === 0) {
    why.push("ไม่มีเคสให้รันเลยสักเคส — 'ไม่มีอะไรพัง' กับ 'ไม่ได้ตรวจอะไร' ให้ผลเหมือนกันเป๊ะ");
  }
  if (s.suiteErrors > 0) {
    why.push(
      `มี suite ที่รันไม่สำเร็จ ${s.suiteErrors} ชุด — เคสข้างในไม่เคยถูกประเมิน\n` +
        "     เกือบทุกครั้งคือ `beforeAll` ล้ม · ดูบรรทัด `Failed Suites` ข้างบน ไม่ใช่บรรทัด `Tests`",
    );
  }
  if (s.skipped > 0) {
    why.push(
      `มีเคสถูกข้าม ${s.skipped} เคส — **การข้ามอ่านเป็นเขียวได้ และนั่นคือทั้งหมดของปัญหา**\n` +
        "     · ไม่มี creds → `set -a && . ./.env.local && set +a` ก่อนรัน\n" +
        "     · `beforeAll` ล้ม → แก้ที่บล็อกนั้น อย่าปล่อยให้มันข้ามต่อไป",
    );
  }
  return why.length === 0 ? null : why.map((w, i) => `  ${i + 1}. ${w}`).join("\n");
}
