import { afterAll, beforeEach, describe, expect, it } from "vitest";
import { localDateIso } from "@/lib/localDate";

/**
 * `lib/localDate.ts` — **ไม่มีเทสต์เลยจนถึง 27 ส.ค. 2026** (P1)
 *
 * ไฟล์นี้มีคอมเมนต์อธิบายบั๊กที่มันกันไว้ละเอียดมาก **แต่ไม่มีอะไรบังคับให้มันยังกันอยู่**
 * 🎯 **คำอธิบายที่ไม่มีเทสต์ค้ำ คือคำอธิบายของสิ่งที่ *เคย* จริง** — และไม่มีใครรู้ตอนมันเลิกจริง
 *
 * ## 🔴 ทำไมไฟล์ 6 บรรทัดนี้เสี่ยงกว่าที่หน้าตาบอก
 * ทริปจริง 11–21 ต.ค. 2026 ข้าม **3 เขตเวลา** (ไทย +7 · เวียดนาม +7 · เกาหลี +9)
 * ถ้าฟังก์ชันนี้ตอบผิด **หน้า `/today` จะโชว์แผนของเมื่อวานตลอดเช้า** และป้าย
 * "จองภายใน 1 วัน" จะขึ้นค้างทุกเช้าจนถึง 09:00 น. — ตอนที่คนกำลังจะออกจากที่พักพอดี
 *
 * ## เทสต์นี้เปลี่ยน `TZ` ตอนรันจริง ไม่ได้พึ่งเขตเวลาของเครื่องที่รัน
 * ⚠️ **จำเป็น** — ถ้าพึ่งเครื่อง เทสต์จะมีความหมายบนเครื่องผมและ**ว่างเปล่าบน CI ที่รันด้วย UTC**
 * (บน UTC ค่าที่ถูกกับค่าที่ผิดเท่ากันเสมอ → บั๊กผ่านฉลุย)
 */

const ORIGINAL_TZ = process.env.TZ;
afterAll(() => { process.env.TZ = ORIGINAL_TZ; });
beforeEach(() => { process.env.TZ = "UTC"; });

describe("localDateIso — วันตามปฏิทินของคนที่ถือเครื่อง", () => {
  /**
   * 🔴 **เคสหลัก: สถานการณ์ที่คอมเมนต์ในไฟล์บรรยายไว้ ทำให้เกิดขึ้นจริง**
   * 16 ต.ค. 2026 เวลา 20:00 UTC = **17 ต.ค. 05:00 ที่โซล**
   * · คนที่ยืนอยู่โซลตอนนั้นต้องเห็นแผนของ **วันที่ 17**
   * · `toISOString().slice(0,10)` ตอบ **วันที่ 16** — คือแผนของเมื่อวาน
   */
  const INSTANT = new Date(Date.UTC(2026, 9, 16, 20, 0, 0));

  it("ที่โซล (+9) เช้ามืด → วันของ *วันนี้* ไม่ใช่ของ UTC", () => {
    process.env.TZ = "Asia/Seoul";
    expect(localDateIso(INSTANT)).toBe("2026-10-17");
    // 🎯 เคสนี้คือทั้งหมดที่ไฟล์นั้นมีไว้ป้องกัน — เขียนไว้ตรง ๆ ให้เห็นว่ามันต่างกันจริง
    expect(INSTANT.toISOString().slice(0, 10)).toBe("2026-10-16");
  });

  it("ที่กรุงเทพ (+7) ตี 3 → ยังเป็นวันที่ 17 เหมือนกัน", () => {
    process.env.TZ = "Asia/Bangkok";
    expect(localDateIso(INSTANT)).toBe("2026-10-17");
  });

  it("ที่ฮานอย (+7) — วันบินขาไป 11 ต.ค. ต้องไม่กลายเป็นวันที่ 10", () => {
    process.env.TZ = "Asia/Ho_Chi_Minh";
    expect(localDateIso(new Date(Date.UTC(2026, 9, 10, 18, 30, 0)))).toBe("2026-10-11");
  });

  it("ที่ UTC → ตรงกับ ISO (ไม่มีอะไรให้ต่าง)", () => {
    expect(localDateIso(INSTANT)).toBe("2026-10-16");
  });

  it("🔴 เขตเวลาติดลบ (ตะวันตกของ UTC) ก็ต้องถูก — แพลตฟอร์มไม่ได้มีแต่เอเชีย", () => {
    process.env.TZ = "America/New_York";
    expect(localDateIso(INSTANT)).toBe("2026-10-16");
    // เที่ยงคืนกว่าที่ UTC = ยังเป็นเมื่อวานที่นิวยอร์ก
    expect(localDateIso(new Date(Date.UTC(2026, 9, 17, 1, 0, 0)))).toBe("2026-10-16");
  });

  describe("รูปแบบสตริง — ต้องเทียบกับ `day.date` ของฐานได้ตรง ๆ", () => {
    it("เดือนและวันเลขเดียวต้องมีศูนย์นำหน้า", () => {
      // ⚠️ ถ้าลืม `padStart` จะได้ `"2026-1-5"` ซึ่ง **เทียบกับ `"2026-01-05"` ไม่ตรง**
      //    แล้วหน้า /today จะหาแผนของวันนั้นไม่เจอ โดยไม่มี error ที่ไหนเลย
      expect(localDateIso(new Date(2026, 0, 5, 12, 0, 0))).toBe("2026-01-05");
      expect(localDateIso(new Date(2026, 11, 31, 23, 59, 59))).toBe("2026-12-31");
    });

    it("เดือนนับจาก 1 ไม่ใช่ 0 (`getMonth()` คืน 0–11)", () => {
      expect(localDateIso(new Date(2026, 0, 1, 12, 0, 0))).toBe("2026-01-01");
      expect(localDateIso(new Date(2026, 9, 11, 12, 0, 0))).toBe("2026-10-11");
    });

    it("ข้ามปีตอนเที่ยงคืน", () => {
      expect(localDateIso(new Date(2026, 11, 31, 23, 59, 59))).toBe("2026-12-31");
      expect(localDateIso(new Date(2027, 0, 1, 0, 0, 0))).toBe("2027-01-01");
    });

    it("29 ก.พ. ปีอธิกสุรทิน", () => {
      expect(localDateIso(new Date(2028, 1, 29, 12, 0, 0))).toBe("2028-02-29");
    });
  });
});
