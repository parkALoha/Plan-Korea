import { describe, expect, it } from "vitest";
import { shouldCacheSideMap } from "@/lib/engine/stopsPayload";
import type { Place } from "@/data/places";

/**
 * `E6-AC13` — side-map ของ `/stops` ลงแคชคีย์แยก (`stopPlaces:<planId>`) · P3 · 2 ก.ย. 2026
 *
 * 🔴 **กฎที่ไฟล์นี้กัน: `{}` ห้ามทับของเดิม**
 * route คืน `places: {}` เมื่อคิวรีคลังล้ม — **จุดแวะยังมาครบ** จึงไม่มีอะไรดูผิดปกติจากฝั่งไคลเอนต์
 * ทับแคชด้วยมัน = คลังล่มหนึ่งครั้ง แล้วผู้ใช้เสียชื่อสถานที่ตอนออฟไลน์จนกว่าจะออนไลน์อีกครั้ง
 * 🎯 **เป็นกฎที่คนถัดไปจะลบทิ้งเพราะมันดูเหมือนเงื่อนไขที่ไม่จำเป็น** — เคสนี้คือสิ่งที่กัน
 */
const place = (id: string) => ({ id }) as unknown as Place;

describe("shouldCacheSideMap", () => {
  it("🔴 `{}` = การเสื่อม ไม่ใช่ข้อมูล → ห้ามเขียนทับ", () => {
    expect(shouldCacheSideMap({})).toBe(false);
  });

  it("มีของ → เขียนได้", () => {
    expect(shouldCacheSideMap({ "busan-bay101": place("busan-bay101") })).toBe(true);
  });

  /**
   * ⚠️ ครอบเท่าที่มันครอบ — ตอบแค่ *"เขียนไหม"*
   * มัน **ไม่ได้** แยก *"คลังล่ม"* ออกจาก *"ทริปนี้ไม่มีจุดแวะที่มาจากคลังเลย"* — สองอย่างนั้น
   * ให้ `{}` เหมือนกันจากฝั่งไคลเอนต์ · ผลลัพธ์ที่ถูกบังเอิญตรงกันทั้งสองกรณี (ไม่เขียนทับ)
   * 🔴 **ถ้าวันหนึ่งต้องแยกสองกรณีนี้ ต้องให้ route บอกมา ไม่ใช่เดาจากขนาดของแมป**
   */
  it("เคสควบคุม — ตัวตรวจต้องไม่ใช่ 'จริงเสมอ' หรือ 'เท็จเสมอ'", () => {
    const results = [shouldCacheSideMap({}), shouldCacheSideMap({ a: place("a") })];
    expect(new Set(results).size, "ให้คำตอบเดียวกันทั้งสองอินพุต = ไม่ได้ตรวจอะไร").toBe(2);
  });
});
