/**
 * วันที่ปฏิทิน **ตามนาฬิกาเครื่องผู้ใช้** ในรูป YYYY-MM-DD
 *
 * ห้ามใช้ `toISOString().slice(0,10)` แทน — นั่นคือวันที่ **UTC** ซึ่งตามหลังไทย 7 ชม. และเกาหลี 9 ชม.
 * ผลของจริง: ยืนอยู่กรุงเทพตอน 06:00 ของวันที่ 17 ก.ย. `toISOString()` ยังบอกว่าเป็นวันที่ 16 อยู่
 * → ตั๋วที่ต้องจอง "วันนี้" ขึ้นป้ายว่า "จองภายใน 1 วัน" ทุกเช้าจนถึง 07:00 น. (ที่เกาหลีถึง 09:00 น.)
 * และหน้า `/today` จะเปิดค้างอยู่ที่แผนของ "เมื่อวาน" ตลอดเช้าวันนั้น
 *
 * ประกอบเองทีละส่วนแทน `toLocaleDateString` เพื่อไม่ต้องพึ่งข้อมูล locale ของ runtime
 * (บาง locale คืนปีพุทธศักราชหรือลำดับวัน/เดือนสลับกัน ซึ่งเทียบกับ `day.date` ไม่ได้)
 *
 * ⚠️ "เครื่อง" คือ timezone ที่มือถือตั้งอยู่ ไม่ใช่ timezone ของจุดหมาย — ตอนอยู่เกาหลีมือถือจะปรับ
 * เป็น KST เองอัตโนมัติ ซึ่งเป็นสิ่งที่เราต้องการ (แผนของวันนั้นตามเวลาเกาหลี) แต่ถ้าใครตั้งมือถือ
 * ค้างไว้ที่เวลาไทยระหว่างเที่ยว จะเห็นแผนวันเก่าต่ออีก 2 ชม. หลังเที่ยงคืนเกาหลี
 */
export function localDateIso(date: Date): string {
  const year = date.getFullYear();
  const month = String(date.getMonth() + 1).padStart(2, "0");
  const day = String(date.getDate()).padStart(2, "0");
  return `${year}-${month}-${day}`;
}
