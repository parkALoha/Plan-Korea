/** สกุลเงินตามรูป ISO-4217 (`THB` · `JPY` · `KRW`) — เก็บเป็นสตริงเพราะเราไม่ได้แปลงค่าเงินเอง */
export type Money = { amount: number; currency: string };

export type OfferKind = "hotel" | "flight" | "activity";

/**
 * ข้อเสนอหนึ่งใบ
 *
 * ⚠️ **`price` เป็น `null` ได้และเป็นสภาพปกติวันนี้** — ผู้เรียกต้องมีทางแสดงกรณีนั้นเสมอ
 * (รูปเดียวกับ `description` ของ `catalogPlaceCards` ที่ `lib/engine/trip.ts:218-221` เตือนไว้)
 */
export type Offer = {
  kind: OfferKind;
  /** id ที่คงที่ของผู้ให้บริการนั้น — ใช้ dedupe ระหว่างผู้ให้บริการไม่ได้ ต่างเจ้าใช้คนละระบบ id */
  id: string;
  title: string;
  /** ราคาต่อหน่วยที่ผู้ให้บริการประกาศ (โรงแรม = ต่อคืน) · `null` = **ยังไม่มีแหล่งราคา** ห้ามเดาแทน */
  price: Money | null;
  /** ลิงก์ที่พาไปจองจริง (มี affiliate tag ในตัว) · `null` = ยังจองผ่านเราไม่ได้ */
  bookingUrl: string | null;
  /** ชื่อผู้ให้บริการที่ตอบใบนี้ — ต้องแสดงให้ผู้ใช้เห็นเสมอเมื่อมีราคา (เขาต้องรู้ว่าราคาของใคร) */
  provider: string;
  lat?: number;
  lng?: number;
  rating?: number;
  reviewCount?: number;
  photoName?: string;
};

/** คำถามที่ส่งให้ผู้ให้บริการ — ช่องที่พักในหน้าแผนรู้ครบทุกช่องนี้อยู่แล้ว */
export type HotelOfferQuery = {
  kind: "hotel";
  /** ชื่อเมืองสำหรับผู้ให้บริการที่ค้นด้วยข้อความ */
  cityName: string;
  lat: number;
  lng: number;
  /** `YYYY-MM-DD` — มาจาก `trip_hotels.check_in`/`check_out` ที่มีอยู่แล้ว */
  checkIn: string;
  checkOut: string;
  guests?: number;
  currency?: string;
};

export type OfferQuery = HotelOfferQuery;

export interface OfferProvider {
  /** ชื่อที่แสดงต่อผู้ใช้ได้ตรง ๆ */
  readonly name: string;
  search(q: OfferQuery): Promise<Offer[]>;
}

/**
 * สถานะของชั้นราคา — **ผู้เรียกต้องแยกสามสถานะนี้ออกจากกัน**
 *
 * 🔴 `unconfigured` ไม่ใช่ `error` และไม่ใช่ `[]`
 * ```
 * unconfigured  ยังไม่ได้ต่อผู้ให้บริการ  → บอกผู้ใช้ว่า "ยังไม่มีราคา" — ไม่ใช่ความผิดพลาด
 * empty         ต่อแล้ว แต่ไม่มีห้องว่าง   → บอกว่า "ไม่มีห้องช่วงนี้" — คนละเรื่องกันคนละฟ้า
 * error         ต่อแล้ว แต่ถามไม่สำเร็จ    → บอกว่าลองใหม่ได้
 * ```
 * 🎯 ***ยุบสามอันนี้เป็น `[]` เดียว = ผู้ใช้เห็น "ไม่มีห้องว่าง" ทั้งที่เราไม่เคยถามใครเลย***
 *    ซึ่งเป็นคำโกหกที่ดูเหมือนข้อมูล · เป็นรูปเดียวกับที่ทีมเจอมาแล้วกับ `grep` ที่ได้ `0`
 *    (แยกไม่ออกระหว่าง *กันไว้แล้ว* · *ยังไม่มีใครลอง* · *มองไม่เห็น*)
 */
export type OfferResult =
  | { state: "unconfigured" }
  | { state: "ok"; offers: Offer[]; provider: string }
  | { state: "empty"; provider: string }
  | { state: "error"; message: string; provider: string };
