import { InviteLanding } from "@/components/InviteLanding";

/**
 * `/invite/<token>` — **หน้าเดียวในเว็บที่ต้องเปิดได้ตอนยังไม่ล็อกอิน นอกจาก `/login`**
 * 🔴 **ห้ามใส่ `requireUser()`** — คนที่ได้ลิงก์มายังไม่มีบัญชีก็ได้
 *    เนื้อหาทั้งหมดมาจาก `peek` ซึ่ง P1 เปิดให้ `anon` โดยตั้งใจ (เห็นแค่ชื่อทริป · คนชวน · สิทธิ์)
 * 📌 ไฟล์นี้บางที่สุดเท่าที่ทำได้ — ตรรกะอยู่ที่ `components/InviteLanding.tsx` (โซน P2)
 *    เพราะ `app/` (routing) เป็นโซน P3 · **แจ้ง P1/P3 แล้วว่าผมวางไฟล์นี้**
 *
 * ## 🔴 **หน้านี้เปิดได้เพราะ `PUBLIC_PATHS` ใน `proxy.ts` — ซึ่งอยู่คนละไฟล์และคนละโซน**
 * ตอนวางไฟล์นี้ครั้งแรก **ผมลืมเรื่องนั้น** ⇒ `/invite/<token>` ตอบ `307 → /login`
 * ***คนที่ได้ลิงก์มาและยังไม่มีบัญชี — คนที่ฟีเจอร์นี้มีไว้เพื่อเขาโดยเฉพาะ — เจอหน้าล็อกอินโดยไม่รู้ว่าทำไม***
 * (P1 เจอตอนไล่ `PUBLIC_PATHS` ด้วยเรื่องอื่น · แก้ที่ `8dfcac7`)
 *
 * 🔴 **ทำไมไม่มีใครจับได้ตอนทดสอบ — ทั้งที่ทดสอบกันสองคน**
 * ```
 * P1 ยิง  **API** ด้วย client เปล่า          ผ่าน
 * P2 ยิง  **หน้า** ด้วย client ที่มีเซสชัน    ผ่าน
 * ของจริง **หน้า** ด้วย client เปล่า          ❌  ← ไม่มีใครยิงช่องนี้
 * ```
 * 🎯 ***สองคนตรวจ ไม่ได้แปลว่าครอบคลุมกว่าหนึ่งคน — ถ้าทั้งคู่ตรึงตัวแปรคนละตัวไว้***
 *
 * ✅ **ก่อนบอกว่าหน้าแบบนี้เสร็จ ต้องยิงแบบนี้เสมอ** (ตรวจได้จากฝั่ง P2 โดยไม่ต้องแตะ `proxy.ts`):
 * ```
 * curl -s -o /dev/null -w "%{http_code} → %{redirect_url}\n" http://localhost:3300/invite/deadbeef
 * ต้องได้ 200 · ได้ 3xx = ยังไม่อยู่ใน PUBLIC_PATHS
 * ```
 * ⚠️ **เครื่องมือที่มีเซสชันอยู่ ทดสอบหน้าแบบนี้ไม่ได้เลยตามนิยาม** — มันขาดคุณสมบัติที่หน้านี้มีไว้เพื่อมัน
 */
export default async function InvitePage({ params }: { params: Promise<{ token: string }> }) {
  const { token } = await params;
  return <InviteLanding token={token} />;
}
