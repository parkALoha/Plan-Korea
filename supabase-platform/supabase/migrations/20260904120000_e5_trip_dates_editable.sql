--   ③ **`insert (… base_timezone …)` ไม่ถูกแตะ** — ไฟล์นี้ปิดเฉพาะ `update`
-- 🎯 ***grant ที่ไม่มีผู้เรียก คือช่องที่เปิดไว้ให้คนที่ไม่ใช่เรา*** — รูปเดียวกับข้อ 6/7 ใน
--    `TEAM.md §3.5` กลับด้าน: ที่นั่นคือสิทธิ์ที่ให้แล้วเรียกไม่ได้ · ที่นี่คือสิทธิ์ที่เรียกได้แต่ไม่มีใครใช้
--
-- 🔴 **มันปลอดภัยวันนี้ด้วยเหตุผลที่ไม่เกี่ยวกับตัวมันเอง — และนั่นคือเหตุผลที่ต้องปิด ไม่ใช่ปล่อย**
--    วันนี้ไม่มีโค้ดไหน *อ่าน* `base_timezone` ไปคำนวณ (ตัวที่ใช้จริงคือ `trip_days.timezone`)
--    ⇒ แก้เป็นค่าขยะก็ยังไม่มีอะไรพัง · **วันที่ `D37` ถูกต่อจนมีตัวอ่าน จะไม่มีอะไรส่งเสียง**
