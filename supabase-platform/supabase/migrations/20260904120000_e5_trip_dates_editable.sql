-- ⚠️ `revoke` ระดับคอลัมน์ **ลบสิทธิ์ระดับตารางไม่ได้** (`20260825122247:64-67`)
--    ที่นี่ปลอดภัยเพราะ `…122247:75` `revoke insert, update on public.trips from authenticated`
--    ล้างสิทธิ์ระดับตาราง (`20260824043822:311`) ไปแล้ว **เหลือแต่ column grant** ⇒ assert ข้างล่างเป็นตัวยืนยัน
--
-- 🔴 **ทะเบียนที่ต้องขยับพร้อมกัน:** `lib/__tests__/rlsMatrix.test.ts` เทียบ `trips.update`
--    กับ ACL จริงจากฐาน ⇒ ต้องถอด `base_timezone` ออกจากรายการนั้นในรอบเดียวกัน
