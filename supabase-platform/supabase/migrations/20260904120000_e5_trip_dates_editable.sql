-- · 📌 ลบทริปเป็นใบแยก และต้องเป็น soft delete (รูปเดียวกับ `soft_delete_trip_hotel`
--   ที่ `20260825150325:124-135`) พร้อมแก้ `trips_select` ให้กรอง `deleted_at`
