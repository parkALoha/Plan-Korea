-- ───────────────────────────────────────────────────────────────────────────
-- 1. เจ้าของทริปแก้ช่วงวันได้
-- ───────────────────────────────────────────────────────────────────────────
-- 🔴 **grant ทีละคอลัมน์ ไม่ใช่ `grant update on public.trips`**
--    `20260825122247:75-79` ตั้งรูปนี้ไว้แล้วโดยตั้งใจ — `trips` มีคอลัมน์ที่ไคลเอนต์ห้ามแตะ
