-- **คำถามที่ตอบ: `base_timezone` *ควร* ให้ไคลเอนต์แก้ไหม → ไม่ควร** และนี่คือของที่วัดได้:
--   ① **ไม่มีผู้เรียก** — `trips.base_timezone` ถูกเขียนที่เดียวคือตอนสร้างทริป ผ่าน
--      `public.create_trip()` ซึ่งเป็น `security definer` (`20260827080000:44,52`)
--      ⇒ รันด้วยสิทธิ์เจ้าของฟังก์ชัน **ไม่ผ่าน grant ของ `authenticated` เลย**
