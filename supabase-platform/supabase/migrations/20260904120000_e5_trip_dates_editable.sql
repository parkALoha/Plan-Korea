  --    ถ้าวันหนึ่งมีคนตั้งใจเปิด เขาจะเห็น assert นี้แดงและรู้ว่าต้องมาแก้ที่นี่ด้วย
  --    ⇒ มติเดิมถูกผูกกับของที่รันได้ ไม่ใช่กับคอมเมนต์ที่หมดอายุเงียบ
