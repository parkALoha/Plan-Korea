-- ⇒ สถานที่จะถูกแจกแยกกันสองเมือง **และไม่มีอะไรฟ้อง** (`legacy_slug` ต่างกัน = ไม่ชน unique)
-- 🎯 ***ปัญหาคือ "ป้ายชื่อ" ไม่ใช่ "ข้อมูลหาย" — แก้ที่ป้าย ไม่ใช่เพิ่มของ***
