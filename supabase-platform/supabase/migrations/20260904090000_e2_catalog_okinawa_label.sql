begin;

do $guard$
begin
  if not exists (
    select 1 from information_schema.tables
    where table_schema = 'app' and table_name = 'project_identity'
  ) then
    raise exception 'ผิดโปรเจกต์: ไม่มี app.project_identity — ฐานนี้ไม่ใช่ engine-dev';
  end if;
  if not exists (
    select 1 from app.project_identity
     where name = 'plan-korea-platform' and ref = 'pmvxwcimjebogjfimzqy' and environment = 'dev'
  ) then
    raise exception 'ผิดโปรเจกต์: app.project_identity มีอยู่ แต่ไม่ใช่ engine-dev';
  end if;
end $guard$;

update public.catalog_cities
   set name_th = 'โอกินาว่า (นาฮะ)'
 where legacy_slug = 'naha';

do $verify$
declare r record;
begin
  select name_th, name_en, name_local into r
    from public.catalog_cities where legacy_slug = 'naha';

  if r is null then raise exception 'ไม่มีแถว naha — ฐานนี้ไม่ใช่ที่ที่คิด'; end if;
  if r.name_th <> 'โอกินาว่า (นาฮะ)' then raise exception 'ชื่อไทยไม่ถูกอัปเดต: %', r.name_th; end if;

  -- 🔴 ข้อสำคัญที่สุดของไฟล์นี้: สองฟิลด์นี้ **ต้องไม่ขยับ**
  --    ถ้าขยับ สถานที่ของเมืองนี้จะแจกไม่เข้าโดยไม่มีอะไรแดง
  if r.name_en <> 'Naha' or r.name_local <> '那覇' then
    raise exception 'name_en/name_local ถูกแก้ด้วย (% / %) — ห้าม ดูเหตุผลที่หัวไฟล์', r.name_en, r.name_local;
  end if;
end $verify$;

commit;
