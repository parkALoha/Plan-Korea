-- ── 🔴 ทำไมแตะแค่ `name_th` ────────────────────────────────────────────────
-- `scripts/catalog-suggest.py:136` จับคู่สถานที่เข้าเมืองด้วย
-- **`name_en` · `name_local` · `name_th`** เทียบกับ `locality`/`admin1` ที่ Google คืนมา
-- · Google คืน locality ของที่ในเมืองว่า **`Naha` / `那覇`**
-- ⇒ **แก้ `name_en` เมื่อไหร่ สถานที่ทั้งเมืองจะแจกไม่เข้าเงียบ ๆ** (ไม่ error · ได้ 0 แถว)
--   ซึ่งเป็นรูปเดียวกับที่ `20260904030000` เจอ: *ผลลบที่มาจากกฎแคบเกิน ไม่ใช่จากข้อมูล*
-- ✅ จึงเก็บ `name_en='Naha'` · `name_local='那覇'` ไว้เหมือนเดิมทั้งคู่ **แตะเฉพาะชื่อที่คนอ่าน**
