-- ── ⚠️ สิ่งที่ไฟล์นี้ *ไม่ได้* แก้ และผู้ใช้ควรรู้ ─────────────────────────
-- โอกินาว่ากว้างกว่านาฮะ — ที่พักตากอากาศจริงอยู่ที่ **อนนะ · ชาตัน · อิชิงากิ · มิยาโกจิมะ**
-- สถานที่แถวนั้น Google จะคืน locality เป็นชื่อเมืองพวกนั้น **ไม่ใช่ `Naha`** ⇒ จะแจกไม่เข้า
-- ทางแก้มี 2 ทาง **ยังไม่ได้ทำทั้งคู่ รอผู้ใช้ตัดสิน**:
--   ① เพิ่มเมืองย่อยเป็นแถวของตัวเอง (เหมาะถ้าจะไปพักที่นั่นจริง)
--   ② เพิ่ม alias ใน `scripts/catalog-suggest.py:92` แบบเดียวกับที่ฮ่องกงใช้กับเขตของมัน
--      (`"Hong Kong": ("kowloon", "hongkongisland", …)`) — **สคริปต์นั้นเป็นของ P1 ต้องผ่านเขา**
