do $verify$
declare n int;
begin
  select count(*) into n from public.catalog_countries where id in ('cn','hk','mo');
  if n <> 3 then raise exception 'ควรมี 3 ประเทศใหม่ แต่มี %', n; end if;

  select count(*) into n from public.catalog_cities where country_id in ('cn','hk','mo');
  if n <> 9 then raise exception 'ควรมี 9 เมืองใหม่ แต่มี %', n; end if;

  -- 🔴 ไม่มีชื่อไหนมีอักขระ Private Use Area (U+E000–U+F8FF)
  select count(*) into n from public.catalog_cities
   where country_id in ('cn','hk','mo')
     and (name_th ~ '[\uE000-\uF8FF]' or name_en ~ '[\uE000-\uF8FF]'
          or coalesce(name_local,'') ~ '[\uE000-\uF8FF]');
  if n > 0 then raise exception 'มีชื่อเมือง % แถวที่มีอักขระ Private Use Area', n; end if;
end $verify$;
