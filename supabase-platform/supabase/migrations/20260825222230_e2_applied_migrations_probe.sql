create or replace function public.applied_migrations()
returns table (version text, name text)
language sql
stable
security definer
set search_path = ''
as $$
  select m.version::text, coalesce(m.name, '')::text
    from supabase_migrations.schema_migrations m
   order by m.version
$$;

